#!/usr/bin/env python3
"""The game's start-up script without the Middle Ages.

    .venv/bin/python westminster/tools/data/build_game_start.py

Vanilla's common/on_action/game_start.txt (on_game_start, on_game_start_after_lobby) is about 7,300 lines, most of
it aimed at historical characters (character:7627, Alfred the Great...) and medieval titles, which don't exist in
Westminster: every new game logged thousands of errors. This copies it and drops each statement that names a
character by number; a title, house, dynasty, faith, culture or map region that Westminster doesn't have;
an event it doesn't have; a set-up effect for medieval history (historical orders, house relations...); or
medieval buildings, holy sites and coat-of-arms swaps. The generic set-up
(global variables, game rules, systems) stays. Westminster's own start-up runs from its wm_*_on_actions.txt files,
which add to these on_actions.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
MOD = ROOT / "westminster"
sys.path.insert(0, str(ROOT.parent / "common" / "tools"))
from ck3paths import GAME  # noqa: E402

REL = Path("common/on_action/game_start.txt")
HEADER = ("# Westminster: Crusader Kings III's own game_start.txt (Paradox Interactive), with every statement about\n"
          "# medieval characters, titles, houses, faiths and cultures removed. Generated by\n"
          "# westminster/tools/data/build_game_start.py - edit there.\n")


def defined_keys():
    """Titles, houses, dynasties, faiths and cultures that exist in Westminster (mod files, or vanilla ones the mod
    doesn't replace for faiths and cultures)."""
    keys = set()
    for f in (MOD / "common" / "landed_titles").glob("*.txt"):
        keys |= set(re.findall(r"\b([ekdcb]_[a-z0-9_]+)\s*=\s*\{", f.read_text(encoding="utf-8-sig")))
    for sub in ("dynasty_houses", "dynasties"):
        for f in (MOD / "common" / sub).glob("*.txt"):
            keys |= set(re.findall(r"^([a-z0-9_]+)\s*=\s*\{", f.read_text(encoding="utf-8-sig"), re.M))
    for f in (MOD / "history/characters").glob("*.txt"):
        keys |= set(re.findall(r"^([a-z0-9_]+)\s*=\s*\{", f.read_text(encoding="utf-8-sig"), re.M))
    for sub in ("religion/religions", "culture/cultures"):
        for base in (GAME, MOD):
            for f in (base / "common" / sub).glob("*.txt"):
                keys |= set(re.findall(r"^\t{0,2}([a-z0-9_]+)\s*=\s*\{", f.read_text(encoding="utf-8-sig"), re.M))
    return keys


def statements(body):
    """Split a block body into top-level statements: (text) chunks, each a whole 'x = { ... }' or 'x = y' line,
    with comments kept with the statement that follows."""
    out, i, n = [], 0, len(body)
    while i < n:
        m = re.compile(r"[^\s#]").search(body, i)
        if not m:
            out.append(body[i:])
            break
        j = m.start()
        # take everything up to the end of this statement
        k, depth = j, 0
        while k < n:
            c = body[k]
            if c == "#":
                k = body.find("\n", k)
                k = n if k < 0 else k
                continue
            if c == '"':
                k = body.find('"', k + 1) + 1
                continue
            if c == "{":
                depth += 1
            elif c == "}":
                depth -= 1
                if depth == 0:
                    k += 1
                    break
            elif c == "\n" and depth == 0 and "=" in body[j:k] and "{" not in body[j:k]:
                break
            k += 1
        out.append(body[i:k])
        i = k
    return out


def available_events():
    """Event ids that exist with Westminster loaded: the mod's events, plus vanilla's in folders the mod doesn't
    replace (replace_path lines in westminster.mod)."""
    replaced = set(re.findall(r'replace_path="(events[^"]*)"', (ROOT / "westminster.mod").read_text()))
    files = list((MOD / "events").rglob("*.txt"))
    for f in (GAME / "events").rglob("*.txt"):
        if str(f.parent.relative_to(GAME)) not in replaced:
            files.append(f)
    ids = set()
    for f in files:
        ids |= set(re.findall(r"^([a-z_0-9]+\.\d+)\s*=\s*\{", f.read_text(encoding="utf-8-sig", errors="replace"), re.M))
    return ids


def regions():
    out = set()
    for f in (MOD / "map_data" / "geographical_regions").glob("*.txt"):
        out |= set(re.findall(r"^([a-z0-9_]+)\s*=\s*\{", f.read_text(encoding="utf-8-sig"), re.M))
    return out


EVENTS, REGIONS = set(), set()
# Set-up effects that only build medieval history (orders, house relations, Japanese blocs...)
HISTORICAL_EFFECT = re.compile(r"\b[a-z0-9_]*historical[a-z0-9_]*_effect\s*=|\btgp_dynasty_house_name_setup_effect\s*="
                               # coats of arms (k_england's Norman lions), medieval buildings and holy sites
                               r"|\bset_coa\s*=|\badd_special_building|\badd_great_building|holy_site")


def refs_missing(code, keys):
    code = re.sub(r"#[^\n]*", "", code)
    # Province ids belong to vanilla's map even when a number happens to exist
    # on ours. Never run historical temple/region setup against Westminster.
    if re.search(r"\b(?:character|province):\d+", code) or HISTORICAL_EFFECT.search(code):
        return True
    if any(r not in REGIONS for r in re.findall(r"\bgeographical_region:([a-z0-9_]+)", code)):
        return True
    if any(r not in REGIONS for r in re.findall(r"\b(?:geographical_region|region)\s*=\s*([a-z0-9_]+)", code)):
        return True
    for ev in re.findall(r"trigger_event\s*=\s*(?:\{[^{}]*?\bid\s*=\s*)?([a-z_0-9]+\.\d+)", code):
        if ev not in EVENTS:
            return True
    return any(key not in keys for _, key in
               re.findall(r"\b(title|house|dynasty|faith|culture|religion|character):([a-z0-9_]+)", code))


HEAD = re.compile(r"\s*(?:#[^\n]*\n\s*)*([^\s=#{}?<>!]+)\s*[?<>!]?=\s*(\{)?")


def clean(body, keys, counts):
    """Drop statements whose head (a scope such as character:7627 = { }, or a plain line) names something Westminster
    doesn't have, and if/else_if blocks whose limit does (with the else branches that follow them). Recurse into
    every other block."""
    parts, skip_else = [], False
    for st in statements(body):
        m = HEAD.match(st)
        if not m:
            parts.append(st)
            continue
        head, is_block = m.group(1), m.group(2) is not None
        if head in ("else_if", "else") and skip_else:
            counts[0] += 1
            continue
        skip_else = False
        if not is_block:
            if refs_missing(st, keys):
                counts[0] += 1
                continue
            parts.append(st)
            continue
        if refs_missing(head, keys):
            counts[0] += 1
            continue
        open_at = st.index("{", m.start(1))
        close_at = st.rindex("}")
        inner = st[open_at + 1:close_at]
        if head.endswith("_county_in_region") and refs_missing(inner, keys):
            counts[0] += 1
            continue
        if head in ("if", "else_if", "trigger_if", "trigger_else_if"):
            lim = re.search(r"limit\s*=\s*\{", inner)
            if lim:
                k, depth = lim.end() - 1, 0
                while True:
                    depth += {"{": 1, "}": -1}.get(inner[k], 0)
                    if depth == 0:
                        break
                    k += 1
                if refs_missing(inner[lim.start():k + 1], keys):
                    counts[0] += 1
                    skip_else = head in ("if", "trigger_if")
                    continue
        parts.append(st[:open_at + 1] + clean(inner, keys, counts) + st[close_at:])
    return "".join(parts)


def main():
    src = (GAME / REL).read_text(encoding="utf-8-sig")
    keys = defined_keys()
    EVENTS.update(available_events())
    REGIONS.update(regions())
    counts = [0]
    out = clean(src, keys, counts)
    dest = MOD / REL
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(HEADER + out, encoding="utf-8-sig")
    print("game_start.txt: %d statements about medieval things removed, %d -> %d lines"
          % (counts[0], src.count("\n"), out.count("\n")))


if __name__ == "__main__":
    main()
