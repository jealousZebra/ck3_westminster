def history_people():
    """Birth year and sex of every character in history/characters (id -> (birth year, female))."""
    out = {}
    for f in (MOD / "history/characters").glob("*.txt"):
        text = f.read_text(encoding="utf-8-sig")
        for m in re.finditer(r"^(wm_[a-z0-9_]+) = \{(.*?)^\}", text, re.M | re.S):
            body = m.group(2)
            b = re.search(r"(\d{4})\.(\d+)\.(\d+) = \{ birth = yes \}", body)
            out[m.group(1)] = (int(b.group(1)) + (int(b.group(2)) - 1) / 12 if b else None, "female = yes" in body)
    return out


def clamp(v):
    return max(0, min(255, int(round(v))))


def set_morph(dna, genes, gene, offset):
    """Morph gene: neutral 128 plus an offset, on the _neg/_pos template that matches the direction."""
    cur = dna.get(gene, (None, 128))[1]
    v = clamp(128 + (cur - 128) * 0.5 + offset)   # keep half of the rolled variation
    t = [k for k in genes[gene] if k.endswith("_neg" if v < 128 else "_pos")]
    dna[gene] = (t[0] if t else next(iter(genes[gene])), v)


def build_dna(cid, p, genes, eth, birth, female):
    age = p.get("portrait_year", START_YEAR) - birth
    rnd = random.Random("wm_likeness_" + re.sub(r"^wm_(1945|1997|2010|2016)_", "wm_historical_", cid))
    dna = sample(resolve(eth, ETHNICITY[p["heritage"]]), rnd)
    # Colours
    hx, hy = HAIR[p["hair"]]
    dna["hair_color"] = (hx + rnd.randint(-3, 3) if hx > 5 else hx, clamp(hy + rnd.randint(-4, 4)))
    sx, sy = SKIN[p["skin"]]
    dna["skin_color"] = (clamp(sx + rnd.randint(-6, 6)), clamp(sy + rnd.randint(-3, 3)))
    ex, ey = EYES[p["eyes"]]
    dna["eye_color"] = (clamp(ex + rnd.randint(-4, 4)), clamp(ey + rnd.randint(-6, 6)))
    # Features: soften the rolled face towards neutral where a feature is described, then add the feature
    extras = {}
    for feat in p.get("face", []):
        for g, v in FEATURES[feat].items():
            if isinstance(g, tuple):
                dna[g[1]] = (v[0], v[1])
            elif g in ("eyebrows", "age"):
                extras[g] = v
            else:
                set_morph(dna, genes, g, v)
    if "eyebrows" in extras:
        shape, fullness = extras["eyebrows"]
        dna["gene_eyebrows_shape"] = (shape, 200)
        dna["gene_eyebrows_fullness"] = (fullness, 200)
    if "age" in extras:
        dna["gene_age"] = (extras["age"][0], clamp(extras["age"][1] * 255))
    # Body
    t, v = BUILD[p.get("build", "average")]
    dna["gene_bs_body_type"] = (t, clamp(v * 255))
    dna["gene_height"] = ("normal_height", clamp(HEIGHT[p.get("height", "average")] * 255 + rnd.randint(-3, 3)))
    # Hair type and baldness. The game balds a man in stages: stage 1 once age/100 >= the gene value, stage 2 once
    # age/200 >= it (gfx/portraits/portrait_modifiers/05_hair_situational.txt)
    curly = p.get("style") in ("short_curly", "tousled")
    dna["gene_hair_type"] = ("hair_afro" if p["heritage"] == "black" else "hair_curly" if curly else "hair_straight", 128)
    bald = p.get("bald", "none")
    if female or age < 18:
        dna["gene_baldness"] = ("no_baldness", 0)
    else:
        # Vanilla has two looks only: a full head of hair, or bald on top (both stages use the same bald hairstyle).
        # A receding hairline can't be shown, so "receding" keeps the hair.
        frac = {"none": None, "receding": None, "thinning": 0.8, "bald": 0.35}[bald]
        dna["gene_baldness"] = ("male_pattern_baldness", 255 if frac is None else clamp(frac * age / 100 * 255))
    beard = p.get("beard", "none")
    dna["gene_body_hair"] = ("body_hair_avg_low_stubble" if beard != "none" else "body_hair_sparse", 128)
    glasses = p.get("glasses") and SHOW_GLASSES
    dna["special_headgear_spectacles"] = ("spectacles", 255) if glasses else ("no_spectacles", 0)
    return dna


def dna_text(key, cid, p, dna):
    order = ["hair_color", "skin_color", "eye_color"]
    lines = ["%s = {\t# %s (%s)" % (key, p["who"], cid), "\tportrait_info = {", "\t\tgenes = {"]
    for g in order:
        x, y = dna[g]
        lines.append("\t\t\t%s={ %d %d %d %d }" % (g, x, y, x, y))
    for g, (t, v) in dna.items():
        if g in order:
            continue
        lines.append('\t\t\t%s={ "%s" %d "%s" %d }' % (g, t, v, t, v))
    # Clothing and the like: the portrait modifiers choose these in play (headgear and cloaks are off everywhere,
    # tools/ui/build_portraits.py); hairstyle and beard come from wm_likenesses.txt
    lines += ['\t\t\thairstyles={ "all_hairstyles" 0 "all_hairstyles" 0 }',
              '\t\t\tbeards={ "no_beard" 0 "no_beard" 0 }',
              '\t\t\tclothes={ "most_clothes" 0 "most_clothes" 0 }',
              '\t\t\theadgear={ "no_headgear" 0 "no_headgear" 0 }',
              '\t\t\tlegwear={ "western_common_legwear" 100 "all_legwear" 0 }',
              '\t\t\tgene_shrink_body={ "shrink_all" 255 "" 0 }',
              '\t\t\tgene_bs_additive_headgears={ "additive_headgears" 255 "" 0 }',
              '\t\t\tgene_bs_cloak_offset={ "cloak_offset" 255 "" 0 }',
              '\t\t\tgene_bs_long_beard={ "long_beard" 255 "" 0 }',
              "\t\t}", "\t}", "\tenabled = yes", "}"]
    return "\n".join(lines)


def template_for(genes, gene, accessory, female):
    """A template of the gene that offers the accessory (all_* first)."""
    # The scripted_character_* templates exist for this (vanilla's historical characters use them); the engine
    # doesn't find a woman's hairstyle in all_hairstyles
    names = sorted(genes[gene], key=lambda t: (not t.startswith("scripted_character"), not t.startswith("all_"), t))
    for t in names:
        if accessory in accessory_list(genes[gene][t], female):
            return t
    raise SystemExit("no %s template offers %s" % (gene, accessory))


def portrait_modifiers(people, genes, hist, override=None):
    """One group: each likeness's hairstyle and beard, chosen for them by id. override: cid -> (hair acc, beard acc)."""
    out = [GEN, "# Hairstyle and beard of each likeness (common/dna_data/wm_likenesses_dna.txt). Vanilla picks these by\n"
           "# culture in play, so a fixed look needs a modifier, as vanilla does for its historical characters\n"
           "# (02_all_historical_characters.txt). Priority 4: above vanilla's base and religious hair, below a player's\n"
           "# own barbershop choice (5) and the situational group that applies baldness (10).\n",
           "wm_likeness_hair = {\n\tusage = game\n\tselection_behavior = max\n\tpriority = 4\n"]
    for cid, p in people.items():
        birth, female = hist[cid]
        age = p.get("portrait_year", START_YEAR) - birth
        if override and cid in override:
            hair, beard = override[cid]
        else:
            style = p.get("style")
            if age < 13:
                hair, beard = None, None            # children keep vanilla's children's hairstyles
            else:
                hair = "none" if style == "shaved" else HAIRSTYLE[style]
                beard = None if female else (BEARD[p.get("beard", "none")] or "none")
        mods = []
        if hair == "none":
            mods.append("\t\t\taccessory = {\n\t\t\t\tmode = add\n\t\t\t\tgene = hairstyles\n\t\t\t\ttemplate = no_hairstyles\n"
                        "\t\t\t\tvalue = 0\n\t\t\t}")
        elif hair:
            mods.append("\t\t\taccessory = {\n\t\t\t\tmode = add\n\t\t\t\tgene = hairstyles\n\t\t\t\ttemplate = %s\n"
                        "\t\t\t\taccessory = %s\n%s\t\t\t}" % (template_for(genes, "hairstyles", hair, female), hair,
                                                 "\t\t\t\ttype = female\n" if female else ""))
        if beard == "none":
            mods.append("\t\t\taccessory = {\n\t\t\t\tmode = add\n\t\t\t\tgene = beards\n\t\t\t\ttemplate = no_beard\n"
                        "\t\t\t\tvalue = 0\n\t\t\t}")
        elif beard:
            mods.append("\t\t\taccessory = {\n\t\t\t\tmode = add\n\t\t\t\tgene = beards\n\t\t\t\ttemplate = %s\n"
                        "\t\t\t\taccessory = %s\n\t\t\t}" % (template_for(genes, "beards", beard, False), beard))
        if not override:
            # Glasses: the DNA gene alone doesn't show them in play
            mods.append("\t\t\taccessory = {\n\t\t\t\tmode = add\n\t\t\t\tgene = special_headgear_spectacles\n"
                        "\t\t\t\ttemplate = %s\n\t\t\t\tvalue = %s\n\t\t\t}" % (
                            ("spectacles", "1") if p.get("glasses") and SHOW_GLASSES else ("no_spectacles", "0")))
        if not mods:
            continue
        out.append("\t%s = {\t# %s\n\t\tdna_modifiers = {\n%s\n\t\t}\n\t\tweight = {\n\t\t\tbase = 0\n"
                   "\t\t\tmodifier = {\n\t\t\t\tadd = 1000\n\t\t\t\texists = this\n\t\t\t\texists = character:%s\n"
                   "\t\t\t\tthis = character:%s\n\t\t\t}\n\t\t}\n\t}" % ("wm_lk_" + cid[3:], p["who"], "\n".join(mods), cid, cid))
    out.append("}\n")
    return "\n".join(out)


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(path, "w", encoding="utf-8-sig", newline="\n") as f:
        f.write(text)
    print("wrote", path.relative_to(ROOT.parent))


