def main():
    genes = load_genes()
    eth = load_ethnicities()
    hist = history_people()
    page = int(sys.argv[sys.argv.index("--page") + 1]) - 1 if "--page" in sys.argv else 0
    if "--catalogue" in sys.argv:
        entries, pm = catalogue_entries(genes, hist)
        write_gallery(entries, page, {"gfx/portraits/portrait_modifiers/wm_gallery_catalogue.txt": pm})
        return
    # Every accessory named in the vocabulary exists
    for acc in [a for a in HAIRSTYLE.values() if a] + [a for a in BEARD.values() if a]:
        gene = "beards" if "beard" in acc else "hairstyles"
        template_for(genes, gene, acc, acc.startswith(("female_", "f_")))
    # A man going bald needs a hairstyle that has a bald version, or the game shows no hair at all
    acc_text = (GAME / "gfx/portraits/accessories/hairstyles.txt").read_text(encoding="utf-8-sig")
    for cid, p in PEOPLE.items():
        if p.get("bald") in ("thinning", "bald") and p.get("style") not in (None, "shaved"):
            acc = HAIRSTYLE[p["style"]]
            block = re.search(r"^%s = \{(.*?)^\}" % acc, acc_text, re.M | re.S).group(1)
            assert "baldness_1" in block, "%s: %s has no bald version; pick another style" % (p["who"], p["style"])
    missing = [c for c in PEOPLE if c not in hist]
    if missing:
        print("not in history yet (run build_2024.py / check wm_royal_family.txt):", missing)
    entries = []
    out = [GEN, "# Likenesses: the DNA of the people a player will recognise, referenced from history with\n"
           "# `dna = wm_dna_<id>`. Each is a face rolled from the game's ethnicities with the person's described looks laid\n"
           "# on top (tools/data/build_likenesses.py). Caricature level: recognisable, never mocking.\n"]
    for cid, p in PEOPLE.items():
        if cid not in hist:
            continue
        birth, female = hist[cid]
        dna = build_dna(cid, p, genes, eth, birth, female)
        for g, (t, v) in [(g, tv) for g, tv in dna.items() if not g.endswith("_color")]:
            assert g in genes and t in genes[g], (cid, g, t)
        out.append(dna_text(DNA_KEYS[cid], cid, p, dna))
        entries.append((cid, p["who"].split(",")[0]))
    write(MOD / "common/dna_data/wm_likenesses_dna.txt", "\n".join(out) + "\n")
    write(MOD / "gfx/portraits/portrait_modifiers/wm_likenesses.txt",
          portrait_modifiers({c: p for c, p in PEOPLE.items() if c in hist}, genes, hist))
    print("likenesses:", len(entries))
    if "--gallery" in sys.argv:
        write_gallery(entries, page)


if __name__ == "__main__":
    main()
