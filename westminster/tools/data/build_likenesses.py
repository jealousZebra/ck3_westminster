def catalogue_entries(genes, hist):
    """Young MPs to model every hairstyle and beard on (by birth year), with the accessory as the label."""
    young_m = sorted([c for c, (b, f) in hist.items() if c.startswith("wm_mp_") and b and b >= 1984 and not f])
    young_f = sorted([c for c, (b, f) in hist.items() if c.startswith("wm_mp_") and b and b >= 1980 and f])
    entries, override = [], {}
    for acc, cid in zip(CATALOGUE_MALE, young_m):
        entries.append((cid, acc))
        override[cid] = (acc, "none")
    for acc, cid in zip(CATALOGUE_FEMALE, young_f):
        entries.append((cid, acc))
        override[cid] = (acc, None)
    for acc, cid in zip(CATALOGUE_BEARD, young_m[len(CATALOGUE_MALE):]):
        entries.append((cid, acc))
        override[cid] = ("male_hair_western_01", acc)
    assert len(young_m) >= len(CATALOGUE_MALE) + len(CATALOGUE_BEARD), len(young_m)
    people = {cid: {"who": lab} for cid, lab in entries}
    return entries, portrait_modifiers(people, genes, hist, override).replace("wm_likeness_hair", "wm_gallery_catalogue")


