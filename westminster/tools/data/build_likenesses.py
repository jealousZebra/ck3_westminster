def load_genes():
    """gene -> {template: block} for every gene in common/genes (morph, accessory and colour genes)."""
    genes = {}

    def walk(items):
        for k, v in items:
            if not isinstance(v, list):
                continue
            tmpl = {tk: tv for tk, tv in v if isinstance(tv, list) and get(tv, "index") is not None}
            if tmpl:
                genes[k] = tmpl
            else:
                walk(v)
    for f in sorted((GAME / "common/genes").glob("*.txt")):
        walk(parse(f.read_text(encoding="utf-8-sig")))
    return genes


def accessory_list(template_block, female):
    """The accessories a template offers for a sex (resolving `female = male` aliases)."""
    key = "female" if female else "male"
    v = get(template_block, key)
    if isinstance(v, str):
        v = get(template_block, v)
    return [a for w, a in (v or []) if a and isinstance(a, str)]


def load_ethnicities():
    eth = {}
    for f in sorted((GAME / "common/ethnicities").glob("*.txt")):
        for k, v in parse(f.read_text(encoding="utf-8-sig")):
            if isinstance(v, list):
                eth[k] = v
    return eth


def resolve(eth, name):
    """An ethnicity's genes, merged over its template chain."""
    items = eth[name]
    base = resolve(eth, get(items, "template")) if get(items, "template") else {}
    out = dict(base)
    for k, v in items:
        if isinstance(v, list):
            out[k] = v
    return out


def sample(spec, rnd):
    """One DNA (gene -> (template, value 0-255) or colour (x, y)) from an ethnicity, as the game would roll it."""
    dna = {}
    for gene, entries in spec.items():
        choices = []
        for w, body in entries:
            try:
                w = float(w)
            except ValueError:
                continue
            if w <= 0 or not isinstance(body, list):
                continue
            if gene.endswith("_color"):
                nums = [float(x) for x, _ in body]
                choices.append((w, nums))
            elif get(body, "traits") is None and get(body, "name"):
                rng = get(body, "range")
                choices.append((w, (get(body, "name"), float(rng[0][0]), float(rng[1][0]))))
        if not choices:
            continue
        pick = rnd.uniform(0, sum(w for w, _ in choices))
        for w, c in choices:
            pick -= w
            if pick <= 0:
                break
        if gene.endswith("_color"):
            x0, y0, x1, y1 = c
            dna[gene] = (round(rnd.uniform(x0, x1) * 255), round(rnd.uniform(y0, y1) * 255))
        else:
            name, a, b = c
            dna[gene] = (name, round(rnd.uniform(a, b) * 255))
    return dna


