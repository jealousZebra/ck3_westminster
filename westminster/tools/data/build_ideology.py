def distance(a, b):
    (x1, y1), (x2, y2) = IDEO[a][6], IDEO[b][6]
    return math.hypot(x1 - x2, y1 - y2)


def nearest(ideo, choices):
    """The ideology in `choices` closest to `ideo` (the first, the mainstream, wins a tie)."""
    if ideo in choices:
        return ideo
    return min(choices, key=lambda c: (distance(ideo, c), choices.index(c)))


def wing_for(ideo, party):
    """(wing id, Commons lean) for a Labour or Conservative MP of this ideology: their ideology's wing, or the
    nearest one in their party. None for other parties."""
    wings = WING_IDEOLOGY.get(party)
    if not wings:
        return None
    return wings[nearest(ideo, list(wings))]


def party_faith(party):
    """The mainstream ideology's faith key of a party (None: Not Stated)."""
    return faith_key(PARTY_RANGE[party][0]) if party in PARTY_RANGE else None


