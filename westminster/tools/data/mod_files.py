"""Shared output conventions for gameplay generators (paths relative to the mod)."""

from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
MOD = ROOT / "westminster"
LANGUAGES = (
    "english",
    "french",
    "german",
    "japanese",
    "korean",
    "polish",
    "russian",
    "simp_chinese",
    "spanish",
)


def generated_header(source):
    return f"# Generated by westminster/tools/data/{source}; edit the generator.\n"


def write_mod_file(path, text):
    target = MOD / path
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(text, encoding="utf-8-sig")
