def people():
    out = {}
    for year, cfg in ERAS.items():
        for name in sorted(
            set(cfg["featured"] + cfg["cabinet"] + list(cfg["leaders"].values()))
        ):
            hair, style, face, bald, glasses, beard = SPECS[name]
            p = dict(
                who=f"{name}, {year} Parliament",
                portrait_year=year + 0.4,
                heritage="white",
                skin="fair",
                eyes="blue",
                hair=hair,
                style=style,
                face=face,
                build=(
                    "stocky"
                    if name
                    in [
                        "Winston Churchill",
                        "Ernest Bevin",
                        "John Prescott",
                        "Gordon Brown",
                        "Boris Johnson",
                    ]
                    else "average"
                ),
                height="average",
            )
            if bald:
                p["bald"] = bald
            if glasses:
                p["glasses"] = True
            if beard:
                p["beard"] = beard
            out[f"wm_{year}_" + norm(name)] = p
    return out
