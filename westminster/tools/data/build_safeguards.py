# Westminster's flow for each re-enabled scheme (wm_intrigue_effects.txt)
FLOW = """	on_phase_completed = {
		wm_intrigue_phase_effect = yes	# Westminster: the moment to act (wm_intrigue_effects.txt)
	}
	on_hud_click = {
		wm_intrigue_hud_click_effect = yes
	}
	on_semiyearly = {
		wm_intrigue_semiyearly_effect = yes
	}
"""


def banned_scheme(name):
    rel = "common/schemes/scheme_types/%s_scheme.txt" % name
    out = sub_once(vanilla(rel), r"^\tallow = \{.*?^\t\}",
                   "\tallow = { always = no }\t# Westminster: never, against anyone", rel)
    write(rel, out, "switched off: real people are never scheme targets")


def flow_blocks(body):
    """Drops vanilla's event-firing pulse blocks and adds Westminster's flow before on_invalidated."""
    for key in ("on_phase_completed", "on_hud_click", "on_monthly", "on_semiyearly"):
        b = find_block(body, key, "\t")
        if b:
            body = body[:b[0]] + body[b[2]:]
    body = re.sub(r"\n[ \t]*\n(?:[ \t]*\n)+", "\n\n", body)
    b = find_block(body, "on_invalidated", "\t")
    return body[:b[0]] + FLOW + body[b[0]:]


AFFAIR_CHECK = ("\t\tcustom_description = {\n\t\t\ttext = wm_intrigue_affair_fictional_only\n\t\t\tobject = scope:target\n"
                "\t\t\tscope:target = { wm_intrigue_affair_target_trigger = yes }\n\t\t}\n")


def seduce_scheme():
    rel = "common/schemes/scheme_types/seduce_scheme.txt"

    def fn(body):
        body = prepend_sub(body, "allow", (
            "\t\t# Westminster: affairs only with fictional characters - never a real person from the bookmark, never\n"
            "\t\t# the royal family, never anyone under 18 (wm_intrigue_triggers.txt)\n" + AFFAIR_CHECK +
            "\t\ttrigger_if = {\n\t\t\tlimit = { is_ai = yes }\n"
            "\t\t\twm_intrigue_affair_ai_owner_trigger = { TARGET = scope:target }\n\t\t}\n"), rel)
        body = prepend_sub(body, "valid", AFFAIR_CHECK, rel)
        # vanilla's on_start fired removed events (incest and house-feud rejections)
        body = replace_sub(body, "on_start", (
            "\ton_start = {\n\t\tset_variable = {\n\t\t\tname = apply_countermeasures\n\t\t\tvalue = flag:opportunistic\n"
            "\t\t}\n\t}"), rel)
        # vanilla's on_invalidated fired removed events: a toast instead
        body = replace_sub(body, "on_invalidated", (
            "\ton_invalidated = {\n\t\tscheme_target_character = { save_scope_as = target }\n"
            "\t\tscheme_owner = {\n\t\t\tsend_interface_toast = {\n\t\t\t\ttype = event_toast_effect_neutral\n"
            "\t\t\t\ttitle = seduce\n\t\t\t\tleft_icon = scope:target\n\t\t\t\tcustom_tooltip = seduce_invalid\n"
            "\t\t\t}\n\t\t}\n\t}"), rel)
        return flow_blocks(body)

    write(rel, edit_object(vanilla(rel), "seduce", fn, rel), "as \"An affair\": fictional targets only")


def fabricate_scheme():
    rel = "common/schemes/scheme_types/fabricate_hook_scheme.txt"

    def fn(body):
        # vanilla needed an intrigue perk (or a fulfilment, tenet, rivalry...): every adult politician may dig
        body = sub_once(body, r"^\tallow = \{\n\t\tOR = \{.*?^\t\t\}\n",
                        "\tallow = {\n\t\t# Westminster: open to every politician (vanilla needed an intrigue perk)\n", rel)
        return flow_blocks(body)

    write(rel, edit_object(vanilla(rel), "fabricate_hook", fn, rel), "as \"Fabricate a Scandal\": open to everyone")


