#!/usr/bin/env python3
"""Safeguards for a game full of real, living people, and vanilla's intrigue in political dress.

    .venv/bin/python westminster/tools/data/build_safeguards.py

Westminster replaces every vanilla events folder, so vanilla's scheme events are gone. This script writes the scheme
and interaction files that still matter, from the installed game's own files (same keys and file names, so everything
that refers to them still loads), with Westminster's changes:

  murder, abduct     common/schemes/scheme_types/{murder,abduct}_scheme.txt: allow = { always = no }, and their
                     interactions hidden (00_scheme_interactions.txt). Never against anyone.
  seduce             "An affair": only aimed at fictional characters (wm_intrigue_affair_target_trigger: not a real
                     person from the bookmark, not the royal family, 18 or over). AI owners must be fictional too.
  fabricate_hook     "Fabricate a Scandal": open to every politician (vanilla needed an intrigue perk).
  expose, blackmail  "Leak to the Press" and "Threaten to Leak" (00_character_interactions.txt,
                     00_blackmail_interactions.txt): political secrets only (wm_intrigue_leakable_secret_trigger), and
                     a leak hurts the target's Profile, their party's poll and public trust (wm_intrigue_leak_effect).

The schemes' vanilla on_phase_completed/on_monthly/... blocks fired the removed events; they are replaced by
Westminster's flow (common/scripted_effects/wm_intrigue_effects.txt, events/wm_intrigue_events.txt). Plot to Oust is
Westminster's own scheme (common/schemes/scheme_types/wm_intrigue_schemes.txt).

Also generated: the list of real people (every character in history/characters with a wm_mp_, wm_royal_ or wm_char_
id): common/scripted_triggers/wm_intrigue_real_people.txt and common/scripted_effects/wm_intrigue_real_people.txt.

Achievements are disabled too: common/achievements/*.txt keep every vanilla achievement's key (the achievement database
stays consistent) but none is possible or can happen, so no achievement unlocks while Westminster is active.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
MOD = ROOT / "westminster"
sys.path.insert(0, str(ROOT.parent / "common" / "tools"))
from ck3paths import GAME  # noqa: E402

BANNED = ["murder", "abduct"]
HEADER = ("# Westminster: Crusader Kings III's own %s (Paradox Interactive),\n# %s.\n"
          "# Generated by westminster/tools/data/build_safeguards.py - edit there.\n")
REAL_PREFIXES = ("wm_mp_", "wm_royal_", "wm_char_", "wm_1979_")

ACH_HEADER = ("# Westminster: Crusader Kings III's own common/achievements/%s (Paradox Interactive), with every achievement\n"
              "# made impossible: no achievements while Westminster is active. Generated by\n"
              "# westminster/tools/data/build_safeguards.py - edit there.\n")


# ---------------------------------------------------------------------------------------------
# Brace-aware editing of Paradox script
# ---------------------------------------------------------------------------------------------
def block_end(text, open_pos):
    """Index just past the '}' matching the '{' at open_pos (skips comments and strings)."""
    depth, i, n = 0, open_pos, len(text)
    while i < n:
        c = text[i]
        if c == "#":
            i = text.find("\n", i)
            if i < 0:
                break
            continue
        if c == '"':
            i = text.find('"', i + 1) + 1
            continue
        if c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1
    sys.exit("unbalanced braces")


def find_block(text, key, indent, start=0):
    """(start, open_brace, end) of the first `<indent>key = {` block in text[start:]."""
    m = re.compile(r"^%s%s\s*=\s*\{" % (re.escape(indent), re.escape(key)), re.M).search(text, start)
    if not m:
        return None
    ob = text.index("{", m.start())
    return m.start(), ob, block_end(text, ob)


def edit_object(text, obj, fn, what):
    """Applies fn(body) to the top-level object `obj = { ... }`."""
    b = find_block(text, obj, "")
    if not b:
        sys.exit("no %s in %s" % (obj, what))
    s, ob, e = b
    return text[:s] + fn(text[s:e]) + text[e:]


def replace_sub(body, key, new, what):
    """Replaces the one-tab `key = { ... }` block inside an object's body."""
    b = find_block(body, key, "\t")
    if not b:
        sys.exit("no %s block in %s" % (key, what))
    return body[:b[0]] + new + body[b[2]:]


def prepend_sub(body, key, lines, what):
    """Inserts lines at the start of the one-tab `key = { ... }` block."""
    b = find_block(body, key, "\t")
    if not b:
        sys.exit("no %s block in %s" % (key, what))
    return body[:b[1] + 1] + "\n" + lines + body[b[1] + 1:]


def sub_once(text, pattern, repl, what, flags=re.M | re.S):
    out, n = re.subn(pattern, repl, text, count=1, flags=flags)
    if n != 1:
        sys.exit("pattern %r not found in %s" % (pattern, what))
    return out


def write(rel, text, note):
    dest = MOD / rel
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(HEADER % (rel, note) + text, encoding="utf-8-sig")


def vanilla(rel):
    return (GAME / rel).read_text(encoding="utf-8-sig")


