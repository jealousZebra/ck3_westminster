def scheme_interactions():
    rel = "common/character_interactions/00_scheme_interactions.txt"
    text = vanilla(rel)
    for obj in ("start_murder_interaction", "start_abduct"):
        text = edit_object(text, obj, lambda b: replace_sub(
            b, "is_shown", "\tis_shown = { always = no }\t# Westminster: murder and abduction are off", rel), rel)

    def seduce(body):
        body = prepend_sub(body, "is_shown", (
            "\t\t# Westminster: affairs only with fictional characters (wm_intrigue_triggers.txt)\n"
            "\t\tscope:recipient = { wm_intrigue_affair_target_trigger = yes }\n"), rel)
        return prepend_sub(body, "is_available", (
            "\t\ttrigger_if = {\n\t\t\tlimit = { is_ai = yes }\n\t\t\twm_intrigue_is_real_person_trigger = no\n\t\t}\n"), rel)
    text = edit_object(text, "seduce_interaction", seduce, rel)
    write(rel, text, "with murder and abduction hidden and seduction limited to fictional characters")


def perk_interactions():
    rel = "common/character_interactions/00_perk_interactions.txt"

    def fn(body):
        # is_shown and is_valid: drop vanilla's perk/fulfilment/tenet gate
        body = sub_once(body, r"^\tis_shown = \{\n\t\tscope:puppet_or_actor \?= \{\n\t\t\tOR = \{.*?^\t\t\}\n",
                        "\tis_shown = {\n\t\t# Westminster: open to every politician\n"
                        "\t\tscope:puppet_or_actor ?= { is_adult = yes }\n", rel)
        body = sub_once(body, r"^\t\tscope:puppet_or_actor = \{\n\t\t\tOR = \{\n\t\t\t\tcustom_tooltip = \{\n"
                              r"\t\t\t\t\ttext = sp_fabricate_hook_court_chaplain_tt.*?^\t\t\}\n", "", rel)
        # the AI digs about once a decade per MP, not every five years
        return sub_once(body, r"(ai_frequency_by_tier = \{.*?county = )60", r"\g<1>120", rel)
    write(rel, edit_object(vanilla(rel), "fabricate_hook_interaction", fn, rel),
          "with Fabricate a Scandal (fabricate_hook_interaction) open to every politician")


