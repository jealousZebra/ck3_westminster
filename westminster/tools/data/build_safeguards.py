def real_people():
    ids = []
    for f in sorted((MOD / "history" / "characters").glob("*.txt")):
        ids += re.findall(r"^((?:%s)\w+)\s*=\s*\{" % "|".join(REAL_PREFIXES), f.read_text(encoding="utf-8-sig"), re.M)
    ids = sorted(set(ids))
    if len(ids) < 600:
        sys.exit("only %d real people found" % len(ids))
    note = ("# Every real person in the bookmark's history (ids %s). Generated by\n"
            "# westminster/tools/data/build_safeguards.py from history/characters - edit there.\n" % ", ".join(REAL_PREFIXES))
    trig = note + ("\n# Character: one of the real people (for saves made before the wm_real_person flags were set)\n"
                   "wm_intrigue_real_list_trigger = {\n\tOR = {\n" +
                   "".join("\t\tthis = character:%s\n" % i for i in ids) + "\t}\n}\n")
    eff = note + ("\n# No scope. Flags the real people (wm_real_person), once per game (wm_intrigue_triggers.txt).\n"
                  "wm_intrigue_mark_real_people_effect = {\n"
                  "\tif = {\n\t\tlimit = { NOT = { has_global_variable = wm_intrigue_real_marked } }\n"
                  "\t\tset_global_variable = { name = wm_intrigue_real_marked value = yes }\n" +
                  # Later-bookmark characters may not have been born yet.
                  "".join("\t\tcharacter:%s ?= { if = { limit = { is_alive = yes } add_character_flag = wm_real_person } }\n" % i for i in ids) + "\t}\n}\n")
    for rel, text in (("common/scripted_triggers/wm_intrigue_real_people.txt", trig),
                      ("common/scripted_effects/wm_intrigue_real_people.txt", eff)):
        (MOD / rel).write_text(text, encoding="utf-8-sig")
    return len(ids)


def disable_achievements():
    n = 0
    for f in sorted((GAME / "common" / "achievements").glob("*.txt")):
        keys = re.findall(r"^([a-z0-9_]+)\s*=\s*\{", f.read_text(encoding="utf-8-sig"), re.M)
        body = "".join("%s = {\n\tpossible = { always = no }\n\thappened = { always = no }\n}\n" % k for k in keys)
        dest = MOD / "common" / "achievements" / f.name
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(ACH_HEADER % f.name + body, encoding="utf-8-sig")
        n += len(keys)
    return n


def main():
    for name in BANNED:
        banned_scheme(name)
    # the 0.3 safeguard switched seduction off entirely; it now comes from seduce_scheme()
    seduce_scheme()
    fabricate_scheme()
    scheme_interactions()
    perk_interactions()
    character_interactions()
    blackmail_interactions()
    print("schemes switched off:", ", ".join(BANNED))
    print("in political dress: fabricate_hook (Fabricate a Scandal), seduce (An affair), "
          "expose/blackmail (Leak to the Press, Threaten to Leak)")
    print("real people listed:", real_people())
    print("achievements disabled:", disable_achievements())


if __name__ == "__main__":
    main()
