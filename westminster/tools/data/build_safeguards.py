#!/usr/bin/env python3
"""Safeguards for a game full of real, living people: vanilla's murder, abduction and seduction schemes are switched
off, so no player can aim them at a real MP or member of the royal family.

    .venv/bin/python westminster/tools/data/build_safeguards.py

Writes common/schemes/scheme_types/{murder,abduct,seduce}_scheme.txt: vanilla's files (same scheme names, so
everything that refers to them still loads) with allow = { always = no }.

Achievements are disabled too: common/achievements/*.txt keep every vanilla achievement's key (the achievement database
stays consistent) but none is possible or can happen, so no achievement unlocks while Westminster is active.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
MOD = ROOT / "westminster"
sys.path.insert(0, str(ROOT.parent / "common" / "tools"))
from ck3paths import GAME  # noqa: E402

SCHEMES = ["murder", "abduct", "seduce"]
HEADER = ("# Westminster: Crusader Kings III's own %s_scheme.txt (Paradox Interactive), switched off: real people\n"
          "# are never scheme targets. Generated by westminster/tools/data/build_safeguards.py - edit there.\n")


ACH_HEADER = ("# Westminster: Crusader Kings III's own common/achievements/%s (Paradox Interactive), with every achievement\n"
              "# made impossible: no achievements while Westminster is active. Generated by\n"
              "# westminster/tools/data/build_safeguards.py - edit there.\n")


def disable_achievements():
    n = 0
    for f in sorted((GAME / "common" / "achievements").glob("*.txt")):
        keys = re.findall(r"^([a-z0-9_]+)\s*=\s*\{", f.read_text(encoding="utf-8-sig"), re.M)
        body = "".join("%s = {\n\tpossible = { always = no }\n\thappened = { always = no }\n}\n" % k for k in keys)
        dest = MOD / "common" / "achievements" / f.name
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(ACH_HEADER % f.name + body, encoding="utf-8-sig")
        n += len(keys)
    return n


def main():
    for name in SCHEMES:
        rel = Path("common/schemes/scheme_types/%s_scheme.txt" % name)
        src = (GAME / rel).read_text(encoding="utf-8-sig")
        out, n = re.subn(r"^\tallow = \{.*?^\t\}", "\tallow = { always = no }\t# Westminster: never against real people",
                         src, count=1, flags=re.M | re.S)
        if n != 1:
            sys.exit("no allow block in %s" % rel)
        dest = MOD / rel
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(HEADER % name + out, encoding="utf-8-sig")
    print("schemes switched off:", ", ".join(SCHEMES))
    print("achievements disabled:", disable_achievements())


if __name__ == "__main__":
    main()
