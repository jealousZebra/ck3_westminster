import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent          # westminster/
OUT = ROOT / "westminster" / "CREDITS.txt"
README = ROOT / "data" / "README.md"
META = ROOT / "data" / "raw" / "flags" / "meta.json"

