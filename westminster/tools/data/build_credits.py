# Authors checked by hand where Commons' "Artist" field says only "Own work" (keyed by Commons page)
AUTHORS = {
    "https://commons.wikimedia.org/wiki/File:Royal_standard_of_the_United_Kingdom.svg":
        "Fry1989 and other Wikimedia Commons contributors (see the file history)",
}


def flags_from_meta():
    """[(flag, title, Commons page, author, licence)] from build_flags.py's FLAGS and the downloaded meta.json."""
    sys.path.insert(0, str(ROOT / "tools" / "ui"))
    from build_flags import FLAGS                          # noqa: E402  (fid -> (search, title, what))
    meta = json.loads(META.read_text(encoding="utf-8"))
    rows = []
    for fid, (_, title, what) in FLAGS.items():
        m = meta[fid]
        lic = m["licence"] + (" (%s)" % m["licence_url"] if m["licence_url"] else "")
        rows.append((what, title, m["page"], m["author"] or "unknown", lic))
    return rows


def flags_from_readme():
    """The same rows from the table build_flags.py writes into data/README.md."""
    text = README.read_text(encoding="utf-8")
    block = re.search(r"<!-- flags:begin.*?<!-- flags:end -->", text, re.S)
    if not block:
        sys.exit("No flags table in %s and no %s: run tools/ui/build_flags.py first." % (README, META))
    rows = []
    for line in block.group(0).splitlines():
        m = re.match(r"\| (.+?) \| `(\w+)` \| \[.*?\]\((\S+)\) \| (.*?) \| (.*?) \|$", line)
        if m:
            rows.append(m.groups())
    return rows


def main():
    rows = flags_from_meta() if META.exists() else flags_from_readme()
    lines = [HEAD.rstrip("\n"), ""]
    for what, title, page, author, lic in rows:
        author = AUTHORS.get(page, author)
        lines.append("- %s (%s): %s" % (what, title, page))
        lines.append("  Author: %s. Licence: %s." % (author.strip().rstrip("."), lic))
    text = "\n".join(lines) + "\n"
    text = text.replace("{", "(").replace("}", ")")           # the static check counts braces in .txt files
    OUT.write_text(text, encoding="utf-8-sig")
    print("wrote %s (%d flags)" % (OUT.relative_to(ROOT.parent), len(rows)))


if __name__ == "__main__":
    main()
