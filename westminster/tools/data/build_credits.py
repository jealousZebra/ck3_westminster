#!/usr/bin/env python3
"""Writes westminster/westminster/CREDITS.txt, the attribution that ships inside the mod.

    .venv/bin/python westminster/tools/data/build_credits.py

The data, font and flag licences (OGL, Open Parliament Licence, CC BY, CC BY-SA, Copernicus, OFL) all ask for
attribution in the distributed work, so it goes in the mod folder, not only in the repo's NOTICE.md. The flag table
comes from data/raw/flags/meta.json (written by tools/ui/build_flags.py) when it has been downloaded, otherwise from
the flags table that build_flags.py keeps in data/README.md. Run after build_flags.py (tools/ui/build_ui.sh does).
The file is UTF-8 with a BOM, like every text file in the mod (common/tools/ck3_checks.py checks).
"""
