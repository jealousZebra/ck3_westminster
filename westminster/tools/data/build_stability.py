#!/usr/bin/env python3
"""Fix vanilla systems whose medieval geography cannot work on Westminster's map.

Run after a CK3 update: .venv/bin/python westminster/tools/data/build_stability.py
Keeps the pool template's traits and skills, but draws its culture from the ruler.
Disables only the Iberian legacy tracks, whose missing-region check ran thousands
of times in the startup log. Other dynasty legacies are unchanged.
"""
import re
from pathlib import Path

from build_safeguards import GAME, MOD, edit_object, replace_sub


HISTORY_TREES = ("history/situations", "history/struggles")


def disable_vanilla_history(game=GAME, mod=MOD):
    """Shadow vanilla history by filename, even with cached pre-0.5.3 metadata.

    Keep replace_path as well: it covers new files added by later game updates.
    Regenerate these overrides after updating CK3.
    """
    for tree in HISTORY_TREES:
        for source in sorted((Path(game) / tree).rglob("*.txt")):
            target = Path(mod) / source.relative_to(game)
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(
                "# Westminster: vanilla situation/struggle history is intentionally disabled.\n"
                "# Its geography does not exist on this map. Filename override protects\n"
                "# subscribers whose launcher has cached older replace_path settings.\n"
                "# Generated by westminster/tools/data/build_stability.py.\n",
                encoding="utf-8-sig")


def write(rel, text):
    p = MOD / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text("# Westminster: adapted from CK3's " + rel + " (Paradox Interactive).\n"
                 "# Generated by westminster/tools/data/build_stability.py - edit there.\n" + text,
                 encoding="utf-8-sig")


def main():
    disable_vanilla_history()
    rel = "common/scripted_character_templates/00_pool_repopulation_character_templates.txt"
    src = (GAME / rel).read_text(encoding="utf-8-sig")
    src = edit_object(src, "pool_repopulate_local_flavor",
                      lambda body: replace_sub(body, "random_culture", "\tculture = root.culture", rel), rel)
    write(rel, src)
    rel = "common/dynasty_legacies/96_fp2_legacies.txt"
    src = (GAME / rel).read_text(encoding="utf-8-sig")
    for key in ("fp2_urbanism_legacy_track", "fp2_coterie_legacy_track"):
        src = edit_object(src, key, lambda body: replace_sub(body, "is_shown",
                          "\tis_shown = { always = no }", rel), rel)
    write(rel, src)
    # Historical battlefield ids belong to vanilla's map. Some overlap our
    # ids and would mark unrelated UK wards; others produce null provinces.
    rel = "common/travel/point_of_interest_types/travel_point_of_interest_types.txt"
    src = (GAME / rel).read_text(encoding="utf-8-sig")
    src = edit_object(src, "poi_battles_historical", lambda body: replace_sub(
        body, "build_province_list", "\tbuild_province_list = { }", rel), rel)
    write(rel, src)
    # English re-terms these traits; retain the game's translated labels in
    # other languages instead of falling back to English or failing parity.
    english = (MOD / "localization/english/replace/wm_terms_ui_l_english.yml").read_text(encoding="utf-8-sig")
    keys = set(re.findall(r"^ (trait_[a-z_]+):", english, re.M))
    for folder in (MOD / "localization").iterdir():
        if not folder.is_dir() or folder.name == "english":
            continue
        values = {}
        for p in (GAME / "localization" / folder.name).rglob("*.yml"):
            for key, val in re.findall(r'^ (trait_[a-z_]+):\d*\s+"([^"\n]*)"', p.read_text(encoding="utf-8-sig"), re.M):
                if key in keys:
                    values[key] = val
        assert set(values) == keys, "Missing vanilla trait translations: " + folder.name
        dest = folder / ("wm_trait_labels_l_" + folder.name + ".yml")
        dest.write_text("l_" + folder.name + ":\n # Generated by build_stability.py from CK3's translated trait names.\n" +
                        "".join(' %s: "%s"\n' % (key, values[key]) for key in sorted(keys)), encoding="utf-8-sig")
    print("Local-flavour characters use the ruler's culture; Iberian legacy tracks hidden.")


if __name__ == "__main__":
    main()
