#!/usr/bin/env python3
"""Switches off vanilla's task contracts, so a landless (adventurer) player only ever sees Westminster's own jobs.

    .venv/bin/python westminster/tools/data/build_contracts.py

Why: vanilla's adventurer contracts ("Regale court with stories", "Transport a VIP", ...) start contract schemes and
travel plans whose progress and outcome events live in vanilla's events/ folders, which Westminster replaces
(replace_path for every events/ folder). Taking one started a scheme that never fired a phase or an outcome ("contract
schemes don't execute"), and a contract that needs travel never finished on arrival, so the camp kept travelling
(the endless travel loop). They are medieval jobs anyway.

Writes common/task_contracts/<vanilla file name>.txt for every vanilla contract file: the same contract keys (so
every vanilla script, scheme and on_action that names one still loads) with the same group and icon, but
valid_to_create = no, so the game never offers them. Westminster's jobs are in wm_career_contracts.txt.
Rerun after a CK3 patch.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
MOD = ROOT / "westminster"
sys.path.insert(0, str(ROOT.parent / "common" / "tools"))
from ck3paths import GAME  # noqa: E402

HEADER = ("# Westminster: Crusader Kings III's own common/task_contracts/%s (Paradox Interactive), with every contract\n"
          "# switched off (never offered): their scheme and travel events are vanilla events Westminster removes.\n"
          "# Generated by westminster/tools/data/build_contracts.py - edit there.\n")


def blocks(text):
    """Top-level `key = { ... }` blocks: (key, body)."""
    out = []
    for m in re.finditer(r"^([a-z0-9_]+)\s*=\s*\{", text, re.M):
        depth, i = 1, m.end()
        while depth and i < len(text):
            c = text[i]
            if c == "#":
                i = text.find("\n", i)
                if i < 0:
                    break
                continue
            depth += (c == "{") - (c == "}")
            i += 1
        out.append((m.group(1), text[m.end():i - 1]))
    return out


def stub(key, body):
    group = re.search(r"^\tgroup\s*=\s*(\S+)", body, re.M)
    icon = re.search(r"^\ticon\s*=\s*(\"[^\"]*\")", body, re.M)
    lines = ["%s = {" % key]
    if group:
        lines.append("\tgroup = %s" % group.group(1))
    if icon:
        lines.append("\ticon = %s" % icon.group(1))
    lines += ["\ttravel = no", "\tvalid_to_create = { always = no }", "\tvalid_to_accept = { always = no }",
              "\tvalid_to_continue = { always = no }", "\tvalid_to_keep = { always = no }",
              "\tweight = { value = 0 }", "}"]
    return "\n".join(lines) + "\n"


def main():
    total = 0
    for f in sorted((GAME / "common" / "task_contracts").glob("*.txt")):
        found = blocks(f.read_text(encoding="utf-8-sig"))
        dest = MOD / "common" / "task_contracts" / f.name
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(HEADER % f.name + "\n" + "\n".join(stub(k, b) for k, b in found), encoding="utf-8-sig")
        total += len(found)
        print("%-40s %3d contracts switched off" % (f.name, len(found)))
    print("total:", total)


if __name__ == "__main__":
    main()
