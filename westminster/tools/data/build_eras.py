#!/usr/bin/env python3
"""Dated Parliaments on the fixed 650-seat map. Never infer a missing affiliation.

ParlParse supplies Commons membership (filter by institution, not just post ID).
1945 party labels are a separately cached, attributed public membership table.
More historical seats than map counties leave some backbenchers unlanded; fewer
seats are filled by explicitly named notional members. Every mapping is audited
in data/snapshots. The 2024 map is a gameplay approximation, not historical geography.
"""
import csv, hashlib, json, re
from pathlib import Path
from build_1979 import norm, display_name, culture_for, score, write, IDEOLOGY

ROOT = Path(__file__).resolve().parents[2]
MOD = ROOT / "westminster"
from era_definitions import ERAS, BIRTHS, PARTY, KEY, MANUAL
from mod_files import LANGUAGES
from character_overrides import faith_for, history_lines

# Copy the 1979 defaults; importing this builder must not change another era.
IDEOLOGY = dict(
    IDEOLOGY,
    green="wm_ideo_green",
    sinn_fein="wm_ideo_irish_republican",
    alliance="wm_ideo_liberal",
    reform="wm_ideo_populist_right",
)


def clean_name(s):
    s = re.sub(r"\[[^]]*\]", "", s)
    s = re.sub(
        r"^(Sir |Hon\. |Rt Hon\. |Dr |Captain |Major |Lt-Col\. |Colonel )", "", s
    )
    return re.sub(r", (Bt|.*Baronet).*", "", s).strip()


def membership(year):
    if year == 1945:
        a = json.loads((ROOT / "data/members_1945_affiliations.json").read_text())[
            "members"
        ]
        for m in a:
            m.update(
                name=clean_name(m["name"]),
                party=PARTY.get(m["affiliation"]),
                female=m["name"]
                in [
                    "Ellen Wilkinson",
                    "Edith Summerskill",
                    "Barbara Ayrton-Gould",
                    "Mabel Ridealgh",
                    "Alice Bacon",
                    "Jean Mann",
                    "Bessie Braddock",
                    "Jennie Lee",
                    "Leah Manning",
                    "Muriel Nichol",
                    "Grace Colman",
                    "Florence Paton",
                    "Lucy Noel-Buxton",
                    "Megan Lloyd George",
                    "Lady Apsley",
                    "Irene Ward",
                    "Thelma Cazalet-Keir",
                    "Mary Sutherland",
                    "Constance Kerr",
                    "Katharine Stewart-Murray",
                    "Norah Runge",
                    "Dorothy Rees",
                    "Catherine McNeill",
                    "Patricia Ford",
                ],
            )
        return a
    p = json.loads((ROOT / "data/raw/parlparse_people.json").read_text())
    people = {x["id"]: x for x in p["persons"]}
    posts = {x["id"]: x for x in p["posts"]}
    date = ERAS[year]["date"]
    date = "-".join(f"{int(x):02}" if i else x for i, x in enumerate(date.split(".")))
    a = []
    for m in p["memberships"]:
        post = posts.get(m.get("post_id"), {})
        if post.get("organization_id") != "house-of-commons" or not m.get(
            "start_date", "9999"
        ) <= date <= m.get("end_date", "0000"):
            continue
        person = people[m["person_id"]]
        name = display_name(person, date)
        # Sex is absent from ParlParse. Featured female politicians are explicit below.
        a.append(
            dict(
                name=name,
                old_seat=post["area"]["name"],
                party=PARTY.get(m.get("on_behalf_of_id")),
                affiliation=m.get("on_behalf_of_id"),
                female=name
                in [
                    "Theresa May",
                    "Harriet Harman",
                    "Amber Rudd",
                    "Justine Greening",
                    "Caroline Lucas",
                    "Margaret Ritchie",
                    "Naomi Long",
                ],
                person_id=m["person_id"],
            )
        )
    assert len(a) in (649, 650, 659), (year, len(a))
    return a


def main():
    modern = list(
        csv.DictReader(open(ROOT / "data/ge2024_results.csv", encoding="utf-8-sig"))
    )
    title_path = MOD / "history/titles/wm_2024_seats.txt"
    text = title_path.read_text(encoding="utf-8-sig")
    text = re.sub(r"\t# BEGIN ERAS .*?\t# END ERAS\n", "", text, flags=re.S)
    histories = {}
    onactions = [
        "# Generated by build_eras.py.",
        "on_game_start_after_lobby = { on_actions = { wm_eras_start } }",
        "wm_eras_start = { effect = {",
    ]
    for year, cfg in ERAS.items():
        a = membership(year)
        female_names = {
            norm(name)
            for name in json.loads((ROOT / "data/female_mps.json").read_text())["names"]
        }
        female_names.update(
            norm(name)
            for name in [
                "Viscountess Davidson",
                "Lady Apsley",
                "Lady Tweedsmuir",
                "Lady Grant of Monymusk",
                "Dame Irene Ward",
                "Dame Joan Vickers",
                "Dame Patricia Hornsby-Smith",
                "Lady Megan Lloyd George",
                "Jennie Adamson",
                "Lady Noel-Buxton",
                "Chris McCafferty",
                "Jennifer Willott",
                "Diana R. Johnson",
                "Elizabeth Truss",
                "Nusrat Ghani",
                "Naseem Shah",
            ]
        )
        cached_gender = {
            norm(name): record[1]
            for name, record in json.loads(
                (ROOT / "data/raw/members_api_1979.json").read_text()
            ).items()
        }
        for record in json.loads(
            (ROOT / "data/raw/members_api_2024.json").read_text()
        ).values():
            cached_gender[norm(record["nameDisplayAs"])] = record["gender"]
        for m in a:
            m["female"] = (
                m["female"]
                or norm(m["name"]) in female_names
                or cached_gender.get(norm(m["name"])) == "F"
            )
        available = {r["title"][2:]: r for r in modern}
        major = set(cfg["featured"] + list(cfg["leaders"].values()) + cfg["cabinet"])
        for m in sorted(a, key=lambda m: (m["name"] not in major, m["name"])):
            if not available:
                m["seat"] = None
                continue
            manual = MANUAL.get(m["name"])
            seat = (
                manual
                if manual in available
                else max(
                    available,
                    key=lambda s: score(m["old_seat"], available[s]["constituency"]),
                )
            )
            m["seat"] = seat
            available.pop(seat)
        for seat, r in available.items():
            a.append(
                dict(
                    name="Notional Member for " + r["constituency"],
                    old_seat="Notional modern-map seat",
                    party=cfg["party"],
                    female=False,
                    seat=seat,
                    notional=True,
                )
            )
        ids = set()
        names = {}
        for m in a:
            cid = f"wm_{year}_" + norm(m["name"])
            if cid in ids:
                cid += "_" + norm(m["old_seat"])
            ids.add(cid)
            m["id"] = cid
            names[m["name"]] = m
            h = int(hashlib.sha1(cid.encode()).hexdigest(), 16)
            m["birth"] = BIRTHS.get(m["name"], f"{year-30-h%30}.{h%12+1}.{h%28+1}")
            m["culture"] = culture_for(m["old_seat"])
        missing = major - names.keys()
        # Historical party presidents outside the Commons are deliberately represented by their Commons leader.
        for name in sorted(missing):
            if name in cfg["featured"] + cfg["cabinet"] or name == cfg["pm"]:
                raise ValueError((year, "Missing major politician", name))
        leaders = {p: names[n]["id"] for p, n in cfg["leaders"].items() if n in names}
        for p in sorted({m["party"] for m in a if m["party"]}):
            if p not in leaders:
                leaders[p] = next(m["id"] for m in a if m["party"] == p and m["seat"])
        pm = names[cfg["pm"]]["id"]
        lines = ["# Generated by build_eras.py. Historical map approximation."]
        loc = []
        for m in a:
            n = m["id"][3:]
            party = m["party"]
            lines += [
                f'{m["id"]} = {{',
                f"\tname = wm_name_{n}",
                "\tdynasty_house = "
                + ("wm_house_party_" + party if party else "wm_house_independent"),
                f'\tculture = {m["culture"]}',
                f'\t{m["birth"]} = {{ birth = yes }}',
            ]
            lines.extend(
                history_lines(
                    m["id"],
                    IDEOLOGY.get(party, "wm_faith_not_stated"),
                    "wm_dna_" + n if m["name"] in major else None,
                )
            )
            if m["female"]:
                lines.append("\tfemale = yes")
            if party:
                lines.append(
                    f'\t{cfg["date"]} = {{ effect = {{ set_variable = {{ name = wm_party value = title:k_party_{party} }} }} }}'
                )
            if m.get("affiliation") == "speaker":
                lines.append(
                    f'\t{cfg["date"]} = {{ effect = {{ add_character_flag = wm_speaker }} }}'
                )
            lines.append("}")
            loc.append(f' wm_name_{n}: "{m["name"].replace(chr(34),chr(39))}"')
        write(MOD / f"history/characters/wm_{year}_mps.txt", "\n".join(lines) + "\n")

        def entry(t, h, liege=None, law=False):
            body = (
                f"\t\tholder = {h}\n"
                + (f'\t\tliege = "{liege}"\n' if liege else "")
                + ("\t\tsuccession_laws = { wm_party_succession_law }\n" if law else "")
            )
            histories.setdefault(t, []).append(f'\t{cfg["date"]} = {{\n{body}\t}}\n')

        for t in [
            "e_united_kingdom",
            "k_england",
            "k_scotland",
            "k_wales",
            "k_northern_ireland",
        ]:
            entry(t, pm)
        # Vacant parties must not inherit the preceding era's leader.
        for p in [
            "labour",
            "conservative",
            "lib_dem",
            "snp",
            "plaid",
            "uup",
            "dup",
            "sdlp",
            "sinn_fein",
            "green",
            "alliance",
            "reform",
            "tuv",
        ]:
            entry(
                "k_party_" + p,
                leaders.get(p, "0"),
                None if p == cfg["party"] else "e_united_kingdom",
                True,
            )
        for m in a:
            if m["seat"]:
                entry(
                    "c_" + m["seat"],
                    m["id"],
                    (
                        None
                        if m["id"] == pm
                        else (
                            "e_united_kingdom"
                            if m["id"] in leaders.values() or not m["party"]
                            else "k_party_" + m["party"]
                        )
                    ),
                )
        bm = [
            f'bm_{year}_{cfg["slug"]} = {{',
            f'\tstart_date = {cfg["date"]}',
            "\tis_playable = yes",
            f"\tgroup = bm_group_{year}",
            "\tweight = { value = 110 }",
        ]
        bloc = [
            f' bm_group_{year}: "{year}"',
            f' bm_{year}_{cfg["slug"]}: "{cfg["title"]}"',
            f' bm_{year}_{cfg["slug"]}_desc: "{cfg["challenge"]}\\n\\nThe historical Commons is adapted to the fixed 650-seat modern map. Seat boundaries and some allocations are notional."',
        ]
        for name, (x, y) in zip(
            cfg["featured"],
            [(335, 315), (510, 780), (880, 295), (1055, 835), (1130, 595)],
        ):
            m = names[name]
            key = f"bookmark_{year}_" + norm(name)
            t = (
                "e_united_kingdom"
                if name == cfg["pm"]
                else (
                    "k_party_" + m["party"]
                    if leaders.get(m["party"]) == m["id"]
                    else "c_" + m["seat"]
                )
            )
            bm += [
                "\tcharacter = {",
                f'\t\tname = "{key}"',
                f'\t\tdynasty_house = wm_house_party_{m["party"]}',
                "\t\ttype = " + ("female" if m["female"] else "male"),
                f'\t\tbirth = {m["birth"]}',
                f"\t\ttitle = {t}",
                "\t\tgovernment = feudal_government",
                f'\t\tculture = {m["culture"]}',
                f'\t\treligion = {faith_for(m["id"], IDEOLOGY.get(m["party"],"wm_faith_not_stated"))}',
                '\t\tdifficulty = "BOOKMARK_CHARACTER_DIFFICULTY_MEDIUM"',
                f'\t\thistory_id = {m["id"]}',
                f"\t\tposition = {{ {x} {y} }}",
                "\t\tanimation = personality_rational",
                "\t}",
            ]
            bloc += [
                f' {key}: "{name}"',
                f' {key}_subheading: "'
                + (
                    "Prime Minister"
                    if name == cfg["pm"]
                    else (
                        "Party leader"
                        if m["id"] in leaders.values()
                        else "Member of Parliament"
                    )
                )
                + '"',
                f' {key}_desc: "{cfg["challenge"]}"',
            ]
        bookmark_file = MOD / f"common/bookmarks/bookmarks/wm_{year}_bookmark.txt"
        previous = (
            bookmark_file.read_text(encoding="utf-8-sig")
            if bookmark_file.exists()
            else ""
        )
        bookmark_text = "\n".join(bm + ["}"]) + "\n"
        for key, x, y in re.findall(
            r'name = "(bookmark_[^"]+)".*?position = \{ (\d+) (\d+) \}', previous, re.S
        ):
            bookmark_text = re.sub(
                r'(name = "' + re.escape(key) + r'".*?position = \{ )\d+ \d+( \})',
                lambda m: m[1] + x + " " + y + m[2],
                bookmark_text,
                flags=re.S,
            )
        write(bookmark_file, bookmark_text)
        write(
            MOD / f"common/bookmarks/groups/wm_{year}_group.txt",
            f'bm_group_{year} = {{ default_start_date = {cfg["date"]} }}\n',
        )
        if year == 2016:
            bloc += [' wm_ukip_name: "UK Independence Party"']
        for lang in LANGUAGES:
            write(
                MOD / f"localization/{lang}/wm_{year}_l_{lang}.yml",
                f"l_{lang}:\n" + "\n".join(loc + bloc) + "\n",
            )
        leans = ["wm_init_" + str(year) + "_seat_leans_effect = {"]
        for m in a:
            if not m["seat"]:
                continue
            winner = KEY.get(m["party"], "ind")
            share = {k: 20 for k in ["lab", "con", "ld"]}
            share[winner] = 520
            leans.append(
                f'\ttitle:c_{m["seat"]} = {{ '
                + " ".join(
                    f"set_variable = {{ name = wm_lean_{p} value = {v} }}"
                    for p, v in share.items()
                )
                + " }"
            )
        write(
            MOD / f"common/scripted_effects/wm_{year}_seat_leans.txt",
            "\n".join(leans + ["}"]) + "\n",
        )
        snapshot = dict(
            year=year,
            **cfg,
            members=a,
            mapping_note="Fixed modern 650-seat map; notional seats and unlanded members marked individually.",
        )
        (ROOT / f"data/snapshots/{year}.json").write_text(
            json.dumps(snapshot, ensure_ascii=False, indent=2) + "\n"
        )
        onactions += [
            f'if = {{ limit = {{ game_start_date = {cfg["date"]} }}',
            "title:e_united_kingdom.holder = {",
        ]
        for post, name in zip(
            ["steward", "spymaster", "marshal", "chancellor", "court_chaplain"],
            cfg["cabinet"],
        ):
            onactions += [
                f"cp:councillor_{post} ?= {{ save_temporary_scope_as = wm_outgoing_minister prev = {{ always_fire_councillor = scope:wm_outgoing_minister }} }}",
                f'assign_councillor_type = {{ type = councillor_{post} target = character:{names[name]["id"]} }}',
            ]
        onactions += ["}"]
        if year == 2010:
            onactions += [
                "set_global_variable = { name = wm_coalition_talks_partner value = title:k_party_lib_dem }",
                "set_global_variable = { name = wm_coalition_senior value = title:k_party_conservative }",
                "set_global_variable = { name = wm_coalition_offer_kind value = 1 }",
                "set_global_variable = { name = wm_coalition_offer_seats value = 1 }",
                "set_global_variable = { name = wm_coalition_offer_policy value = 1 }",
                "wm_coalition_form_effect = yes",
            ]
        if year == 2016:
            onactions += ["title:k_party_reform = { set_title_name = wm_ukip_name }"]
        onactions += ["}"]
        print(year, "members", len(a), "landed", sum(bool(m["seat"]) for m in a))
    for title, entries in histories.items():
        block = (
            "\t# BEGIN ERAS (generated by build_eras.py)\n"
            + "".join(entries)
            + "\t# END ERAS\n"
        )
        text, n = re.subn(
            r"^" + re.escape(title) + r" = \{\n",
            lambda m: m[0] + block,
            text,
            count=1,
            flags=re.M,
        )
        assert n == 1, title
    write(title_path, text)
    write(
        MOD / "common/on_action/wm_eras_on_actions.txt",
        "\n".join(onactions + ["}", "}"]) + "\n",
    )


if __name__ == "__main__":
    main()
