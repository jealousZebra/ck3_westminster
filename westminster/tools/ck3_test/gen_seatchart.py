#!/usr/bin/env python3
"""Writes the seat chart's screenshot steps into the harness (harness/common/scripted_effects/rf_test_effects.txt):
step 1 opens the polls panel on The Chamber, step 2 on the Poll Tracker, step 3 on the Latest Poll. Used with
common/ck3_test/ui_walkthrough.sh on the Westminster test save (load it as the last save first: see
tools/ck3_test/shoot_seatchart.sh):

    python3 westminster/tools/ck3_test/gen_seatchart.py
    westminster/tools/ck3_test/shoot_seatchart.sh westminster/tools/test_out/seatchart
"""
import os
from pathlib import Path

OUT = Path(os.environ.get("RFT_OUT") or Path(__file__).resolve().parent / "harness/common/scripted_effects/rf_test_effects.txt")
OUT.write_text("""# Generated by westminster/tools/ck3_test/gen_seatchart.py - edit there.
rf_test_effect = {
	debug_log = "RFT start"
	if = {
		limit = { NOT = { has_global_variable = wm_poll_lab } }
		wm_election_init_effect = yes
	}
	wm_majority_reset_effect = yes
	wm_seatchart_weekly_effect = yes
	every_player = {
		set_variable = { name = wm_ui_polls_open value = yes }
		remove_variable = wm_ui_tab_chamber
		remove_variable = wm_ui_tab_tracker
		if = {
			limit = { global_var:rf_test_step = 1 }
			set_variable = { name = wm_ui_tab_chamber value = yes }
		}
		else_if = {
			limit = { global_var:rf_test_step = 2 }
			set_variable = { name = wm_ui_tab_tracker value = yes }
		}
	}
	wm_ui_count_seats_effect = yes
	debug_log = "RFT done"
}
rf_test_effect_later = {
}
""", encoding="utf-8-sig")
print("wrote", OUT)
