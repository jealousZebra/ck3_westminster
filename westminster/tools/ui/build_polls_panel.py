#!/usr/bin/env python3
"""The polls panel: a newspaper-style box opened from a button on the left edge (the newspaper icon), with three
tabs:

  Latest Poll   each party's national vote share and seats
  The Chamber   the Commons seat chart: government and opposition benches facing each other across the aisle, seats
                coloured by party, the Speaker's chair, the majority line (326) and the working majority
  Poll Tracker  vote shares and seats now, a week ago, and 4 weeks, 3, 6 and 9 months and a year ago

    .venv/bin/python westminster/tools/ui/build_polls_panel.py

Poll shares come from the polls system's global variables (global_var:wm_poll_<party>, tenths of a percent) and
seats from wm_election_count_seats_effect (global_var:wm_seats_<party>), counted when the panel opens, not every
frame. The seat chart's layout is computed in script when the panel opens (wm_seatchart_compute_effect): each bench
is 5 rows of 90 seats, filled column by column from the Speaker's end, front row first, each side's parties in a
fixed order. Each row is a stack of progress bars, one per party (cumulative seats, the largest drawn first), under a
stencil of newsprint with a hole for every seat (gfx/interface/wm_seatchart_stencil.dds).

The tracker's history is kept by the weekly watcher (event wm_majority.100, wm_seatchart_weekly_effect): the values
a week ago (global_var:wm_sc_wk_<key>, the tick before last) and a ring of 14 four-weekly snapshots
(wm_sc_m<i>_<key>, i = 0 the latest, 13 a year before it). Keys: p_<party> polls, s_<party> seats, maj the working
majority (wm_majority_effects.txt).

Writes: common/script_values/wm_ui_polls_values.txt, common/scripted_effects/wm_ui_polls_effects.txt,
common/scripted_guis/wm_ui_polls_guis.txt, common/script_values/wm_seatchart_values.txt,
common/scripted_effects/wm_seatchart_effects.txt, gui/wm_polls.gui, gui/scripted_widgets/wm_ui_widgets.txt,
gfx/interface/wm_seatchart_stencil.dds, localization/english/wm_ui_polls_l_english.yml.
"""
