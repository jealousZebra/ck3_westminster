def write(rel, text):
    p = MOD / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8-sig")


def current(key):
    """Script for a key's current value (needs fresh seat counts and the majority)."""
    if key == "maj":
        return "{ value = wm_majority_value }"
    kind, c = key.split("_", 1)
    var = ("wm_poll_" if kind == "p" else "wm_seats_") + c
    return "{ value = 0 if = { limit = { has_global_variable = %s } value = global_var:%s } }" % (var, var)


def gv(name):
    return "{ value = 0 if = { limit = { has_global_variable = %s } value = global_var:%s } }" % (name, name)


def build_values():
    out = [HEAD, "# The Latest Poll tab: share in percent (one decimal) and seats.\n"]
    for c, _, _, _ in PARTIES:
        out.append("wm_ui_poll_%s = {\n\tvalue = 0\n\tif = {\n\t\tlimit = { has_global_variable = wm_poll_%s }\n"
                   "\t\tvalue = global_var:wm_poll_%s\n\t\tdivide = 10\n\t}\n}\n" % (c, c, c))
        out.append("wm_ui_seats_%s = %s\n" % (c, gv("wm_seats_" + c)))
    out.append("wm_ui_seats_ind = %s\nwm_ui_seats_spk = %s\n" % (gv("wm_seats_ind"), gv("wm_seats_spk")))
    write("common/script_values/wm_ui_polls_values.txt", "".join(out))

    sv = [HEAD, "# The seat chart and the poll tracker (tools/ui/build_polls_panel.py has the layout).\n\n"]
    sv.append("# Seats in row R of a bench (front row 0) covered by the first K parties along it: seats are numbered\n"
              "# column by column, so row R holds seats R, R+5, R+10... Side g the government, o the opposition.\n")
    for side in "go":
        for r in range(ROWS_PER_BENCH):
            for k in range(len(CHART)):
                sv.append("wm_sc_row_%s_%d_%d = {\n\tvalue = 0\n\tif = {\n\t\tlimit = { has_global_variable = wm_sc_%sc_%d }\n"
                          "\t\tvalue = global_var:wm_sc_%sc_%d\n\t\tadd = %d\n\t\tdivide = %d\n\t\tfloor = yes\n"
                          "\t\tmin = 0\n\t\tmax = %d\n\t}\n}\n" % (side, r, k, side, k, side, k, ROWS_PER_BENCH - 1 - r,
                                                                ROWS_PER_BENCH, COLS))
    sv.append("\n# The headline numbers\n")
    sv.append("wm_sc_gov_seats = %s\nwm_sc_opp_seats = %s\n" % (gv("wm_sc_gov_total"), gv("wm_sc_opp_total")))
    sv.append("wm_sc_short_by = {\n\tvalue = 0\n\tsubtract = wm_majority_value\n\tadd = 1\n\tdivide = 2\n\tceiling = yes\n}\n")
    sv.append("\n# The tracker's cells: polls in percent, seats, the working majority\n")
    for label, slot in ROWS:
        for key in KEYS:
            name = "wm_sc_cell_%s_%s" % (label.lower(), key)
            if slot is None:
                src = current(key)
            else:
                src = gv("wm_sc_%s_%s" % ("wk" if slot == "wk" else "m%d" % slot, key))
            if key.startswith("p_"):
                sv.append("%s = {\n\tvalue = %s\n\tdivide = 10\n}\n" % (name, src))
            else:
                sv.append("%s = %s\n" % (name, src))
    write("common/script_values/wm_seatchart_values.txt", "".join(sv))


