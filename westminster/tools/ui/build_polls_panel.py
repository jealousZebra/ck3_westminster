def stencil():
    """Newsprint with a round hole for every seat: the party colours below show through."""
    im = Image.new("RGBA", (BENCH_W, BENCH_H), PAPER + (255,))
    d = ImageDraw.Draw(im)
    off = (PITCH - DOT) / 2
    for r in range(ROWS_PER_BENCH):
        for c in range(COLS):
            x, y = c * PITCH + off, r * PITCH + off
            d.ellipse([x, y, x + DOT - 1, y + DOT - 1], fill=(0, 0, 0, 0))
    out = MOD / "gfx/interface/wm_seatchart_stencil.dds"
    out.parent.mkdir(parents=True, exist_ok=True)
    im.save(out)        # uncompressed RGBA: the holes stay crisp


def rule(w, h=1, color=INK):
    return 'widget = { size = { %d %d } icon = { size = { 100%% 100%% } texture = "gfx/interface/colors/white.dds" color = { %s 1 } } }' % (w, h, color)


def text(key, w, h=20, align="left", fmt="#high", extra=""):
    return ('text_single = { text = "%s" autoresize = no size = { %d %d } align = %s|nobaseline default_format = "%s" %s}'
            % (key, w, h, align, fmt, extra))


def bench(side):
    """One bench: 5 rows of progress bars (largest cumulative first), the stencil on top. Front row nearest the aisle:
    the government's bench sits above the aisle, so its front row is the bottom one."""
    rows = []
    for r in range(ROWS_PER_BENCH):
        y = (ROWS_PER_BENCH - 1 - r) * PITCH if side == "g" else r * PITCH
        bars = []
        for k in range(len(CHART) - 1, -1, -1):
            rr, gg, bb = CHART[k][3]
            bars.append('\t\t\tprogressbar = { size = { %d %d } texture = "gfx/interface/colors/white.dds" color = { %.2f %.2f %.2f 1 } '
                        'min = 0 max = %d value = "[FixedPointToFloat( EmptyScope.ScriptValue(\'wm_sc_row_%s_%d_%d\') )]" }\n'
                        % (BENCH_W, PITCH, rr, gg, bb, COLS, side, r, k))
        rows.append("\t\twidget = {\n\t\t\tposition = { 0 %d }\n\t\t\tsize = { %d %d }\n%s\t\t}\n" % (y, BENCH_W, PITCH, "".join(bars)))
    return ("widget = {\n\t\tsize = { %d %d }\n"
            '\t\ticon = { size = { 100%% 100%% } texture = "gfx/interface/colors/white.dds" color = { %s 1 } }\n'
            "%s"
            '\t\ticon = { size = { 100%% 100%% } texture = "gfx/interface/wm_seatchart_stencil.dds" }\n'
            "\t}" % (BENCH_W, BENCH_H, EMPTY, "".join(rows)))


