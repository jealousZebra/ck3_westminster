# ---------------------------------------------------------------- pictograms

def generate(subject, key):
    job = fal_images.request("https://queue.fal.run/" + MODEL, key,
                             {"prompt": subject + ", " + STYLE, "image_size": fal_images.SIZES["square"],
                              "num_inference_steps": 32, "num_images": 1, "enable_safety_checker": True})
    for _ in range(120):
        if fal_images.request(job["status_url"], key).get("status") == "COMPLETED":
            break
        time.sleep(2)
    else:
        raise TimeoutError("fal job did not finish")
    return fal_images.request(job["response_url"], key)["images"][0]["url"]


def fetch(n, key):
    """Download a generation and cache it as JPEG (quality 90, progressive, like the other art)."""
    with urllib.request.urlopen(generate(PICTOS[n], key), timeout=120) as r:
        im = Image.open(io.BytesIO(r.read())).convert("RGB")
    im.save(CACHE / ("stat_%s.jpg" % n), quality=90, progressive=True)


def crop_mask(a):
    ys, xs = np.nonzero(a > 0.3)
    if not len(ys):
        raise ValueError("empty pictogram")
    return Image.fromarray((a[ys.min():ys.max() + 1, xs.min():xs.max() + 1] * 255).astype(np.uint8))


def silhouette(raw, band=None):
    """Black-on-white pictogram -> alpha mask cropped to the ink (only grey levels within band, if given)."""
    g = np.array(Image.open(raw).convert("L")).astype(np.float32)
    if band is None:
        return crop_mask(np.clip((191 - g) / 115, 0, 1))
    lo, hi = band
    a = np.clip((hi - g) / 16 + 0.5, 0, 1) * (np.clip((g - lo) / 16 + 0.5, 0, 1) if lo > 0 else 1)
    return crop_mask(a)


def pound_mask():
    """A bold serif pound sign in the mod's newspaper face."""
    font = ImageFont.truetype(str(FONT), 800)
    im = Image.new("L", (1000, 1100), 0)
    ImageDraw.Draw(im).text((500, 560), "£", fill=255, font=font, anchor="mm")
    return crop_mask(np.array(im).astype(np.float32) / 255)


_MASKS = {}


def mask(picto):
    if picto not in _MASKS:
        _MASKS[picto] = pound_mask() if picto == "pound" else silhouette(CACHE / ("stat_%s.jpg" % picto),
                                                                         INK_BAND.get(picto))
    return _MASKS[picto]


def reach(m):
    a = np.array(m) > 76
    ys, xs = np.nonzero(a)
    return float(np.sqrt((ys - (a.shape[0] - 1) / 2) ** 2 + (xs - (a.shape[1] - 1) / 2) ** 2).max())


# ---------------------------------------------------------------- drawing (at 8x, scaled down)

def paste_mark(im, m, colour, scale, centre, reach_frac=REACH):
    s = im.width
    f = min(s * scale / max(m.size), s * reach_frac / reach(m))
    m = m.resize((max(1, round(m.width * f)), max(1, round(m.height * f))), Image.LANCZOS)
    layer = Image.new("RGBA", m.size, colour + (255,))
    layer.putalpha(m)
    im.alpha_composite(layer, (int(centre[0] - m.width / 2), int(centre[1] - m.height / 2)))


def draw_gauge(im, level, colour):
    """A dial: a thick paper arc with ticks, a needle that rises with the level (0-3), and a hub."""
    s = im.width
    d = ImageDraw.Draw(im)
    cx, cy = s / 2, s * 0.56
    r = s * 0.28
    w = s * 0.075
    d.arc((cx - r, cy - r, cx + r, cy + r), 180 + 0, 360, fill=colour + (255,), width=int(w))
    for t in range(5):                                       # ticks across the arc
        ang = np.radians(180 + t * 45)
        r0, r1 = r - w * 1.9, r - w * 1.2
        d.line((cx + r0 * np.cos(ang), cy + r0 * np.sin(ang), cx + r1 * np.cos(ang), cy + r1 * np.sin(ang)),
               fill=colour + (255,), width=int(s * 0.03))
    ang = np.radians(180 + 20 + level * (140 / 3))
    tip = (cx + r * 0.92 * np.cos(ang), cy + r * 0.92 * np.sin(ang))
    nx, ny = -np.sin(ang), np.cos(ang)
    b = s * 0.035
    d.polygon([tip, (cx + nx * b, cy + ny * b), (cx - nx * b, cy - ny * b)], fill=colour + (255,))
    h = s * 0.06
    d.ellipse((cx - h, cy - h, cx + h, cy + h), fill=colour + (255,))
    d.rectangle((cx - r, cy + s * 0.1, cx + r, cy + s * 0.1 + w * 0.9), fill=colour + (255,))   # base bar


def arrow_tab(im, kind, colour):
    """A small round tab on the ring with an up (top right) or down (bottom right) arrow."""
    s = im.width
    d = ImageDraw.Draw(im)
    up = kind == "up"
    cx, cy, r = s * 0.79, s * (0.21 if up else 0.79), s * 0.2
    d.ellipse((cx - r, cy - r, cx + r, cy + r), fill=INK + (255,))
    r2 = r - s * 0.035
    d.ellipse((cx - r2, cy - r2, cx + r2, cy + r2), fill=colour + (255,))
    a, g = s * 0.1, -1 if up else 1                          # g: the arrow's direction (screen y)
    d.polygon([(cx, cy + g * a), (cx - a, cy + g * a * 0.05), (cx + a, cy + g * a * 0.05)], fill=PAPER + (255,))
    y0, y1 = sorted((cy + g * a * 0.1, cy - g * a * 0.9))
    d.rectangle((cx - a * 0.38, y0, cx + a * 0.38, y1), fill=PAPER + (255,))


def badge(stat, w, h=None, ring=INK, disc=None, mark=None, shrink=1.0, pips=0, tab=None, level=None, coin=False):
    """One stat's badge at w x h: ink (or level) ring, paper hairline, disc, pictogram; optional pips and tab.
    disc and mark override the stat's colours; shrink scales its pictogram."""
    h = h or w
    size = min(w, h)
    s = size * 8
    picto, base_disc, colour, scale = STATS[stat]
    disc, colour, scale = disc or base_disc, mark or colour, scale * shrink
    im = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    edge = s * EDGE
    d.ellipse((edge, edge, s - edge, s - edge), fill=ring + (255,))
    ring_w = s * RING
    d.ellipse((ring_w, ring_w, s - ring_w, s - ring_w), fill=PAPER + (255,))
    if disc != PAPER:
        inner = ring_w + s * HAIR
        d.ellipse((inner, inner, s - inner, s - inner), fill=disc + (255,))
    if coin:                                                 # Funds: an inner rim, like a coin's
        c = s * 0.2
        d.ellipse((c, c, s - c, s - c), outline=colour + (255,), width=int(s * 0.025))
    if pips:                                                 # level pips on the lower ring
        pr = s * 0.024
        rr = (s / 2 - edge + (s / 2 - ring_w)) / 2
        dot = PAPER if ring in (INK, RED) else INK
        span = min(150, 26 * (pips - 1))
        for i in range(pips):
            ang = np.radians(90 + (span / 2 - (span * i / (pips - 1) if pips > 1 else 0)))
            px, py = s / 2 + rr * np.cos(ang), s / 2 + rr * np.sin(ang)
            d.ellipse((px - pr, py - pr, px + pr, py + pr), fill=dot + (255,))
    if picto == "gauge":
        draw_gauge(im, 2 if level is None else level, colour)
    else:
        paste_mark(im, mask(picto), colour, scale, (s / 2, s / 2))
    if tab:
        arrow_tab(im, *tab)
    im = im.resize((size, size), Image.LANCZOS)
    if (w, h) != (size, size):
        out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        out.alpha_composite(im, ((w - size) // 2, (h - size) // 2))
        im = out
    return im


def flat(stat, w, h=None):
    """The bare pictogram in ink, for vanilla's monochrome flat icons."""
    h = h or w
    s = min(w, h) * 8
    im = Image.new("RGBA", (s, s), (0, 0, 0, 0))
    paste_mark(im, mask(STATS[stat][0]), (0, 0, 0), 0.86, (s / 2, s / 2), reach_frac=0.48)
    im = im.resize((min(w, h),) * 2, Image.LANCZOS)
    out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    out.alpha_composite(im, ((w - im.width) // 2, (h - im.height) // 2))
    return out


def strip(w, h, frames):
    """Frames side by side at vanilla's frame boundaries (frame i covers round(i*w/n) .. round((i+1)*w/n))."""
    n = len(frames)
    out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    for i, make in enumerate(frames):
        x0, x1 = round(i * w / n), round((i + 1) * w / n)
        if make is not None:
            out.alpha_composite(make(x1 - x0, h), (x0, 0))
    return out


def level_badge(stat, lv, pad=1.0):
    """pad < 1 leaves a transparent margin, for textures the GUI draws larger than their slot (vanilla's piety
    icons have a 12% margin, and the top bar's Political Capital badge was clipped without one)."""
    def make(w, h=None):
        h = h or w
        im = badge(stat, round(w * pad), round(h * pad), ring=LEVEL_RINGS[lv], pips=lv if lv >= 2 else 0,
                   disc=(150, 146, 140) if lv == 0 else None)
        out = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        out.alpha_composite(im, ((w - im.width) // 2, (h - im.height) // 2))
        return out
    return make


def pressure(lv, **kw):
    return lambda w, h=None: badge("pressure", w, h, disc=PRESSURE_DISCS[lv], level=lv, **kw)


def modifier(stat, kind):
    disc = {"positive": GREEN, "negative": RED, "mixed": AMBER}[kind]
    tab = {"positive": ("up", GREEN), "negative": ("down", RED), "mixed": None}[kind]
    colour = INK if kind == "mixed" else PAPER
    return lambda w, h=None: badge(stat, w, h, disc=disc, mark=colour, shrink=0.9 if tab else 1, tab=tab, level=2)


def plain(stat, **kw):
    return lambda w, h=None: badge(stat, w, h, coin=stat == "funds", **kw)


