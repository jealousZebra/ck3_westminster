#!/usr/bin/env python3
"""Ranks and tiers renamed for British politics, for every culture and government.

    .venv/bin/python westminster/tools/ui/build_ranks.py

Vanilla names ranks per culture and government (count_feudal_male_english = "Earl", jarl, ...). Every rank or tier key
in vanilla's culture title files gets the Westminster name: Councillor, MP, Regional Leader, First Minister, Prime
Minister; Ward, Constituency, Region, Nation, United Kingdom. Royal-family titles (Prince, Princess and each culture's) are blanked. Writes
localization/english/replace/wm_ranks_l_english.yml.
(The Crown's own "King"/"Queen" keys, king_wm_crown_*, aren't vanilla's and are left alone.)
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
MOD = ROOT / "westminster"
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "common" / "tools"))
from ck3paths import GAME  # noqa: E402  (CK3_GAME_DIR overrides the Steam default)
LOC = GAME / "localization" / "english"
FILES = [LOC / "culture" / "culture_titles_l_english.yml", LOC / "dlc" / "tgp" / "dlc_tgp_cultural_titles_l_english.yml"]

RANKS = {"baron": "Councillor", "count": "MP", "duke": "Regional Leader", "king": "First Minister",
         "emperor": "Prime Minister", "barony": "Ward", "county": "Constituency", "duchy": "Region",
         "kingdom": "Nation", "empire": "United Kingdom"}
PLURALS = {"Councillor": "Councillors", "MP": "MPs", "Regional Leader": "Regional Leaders",
           "First Minister": "First Ministers", "Prime Minister": "Prime Ministers", "Ward": "Wards",
           "Constituency": "Constituencies", "Region": "Regions", "Nation": "Nations", "United Kingdom": "Unions"}


def write_party_leader_flavour(keys):
    """A party leader's rank is "Leader", not the kingdom tier's "First Minister": flavorization for the holders of the
    party titles (common/landed_titles/10_wm_parties.txt). A PM's primary title is the UK, so they stay Prime Minister."""
    titles = (MOD / "common/landed_titles/10_wm_parties.txt").read_text(encoding="utf-8-sig")
    parties = sorted(set(re.findall(r"^(k_party_[a-z0-9_]+) = \{", titles, re.M)))
    out = ["# Generated by westminster/tools/ui/build_ranks.py - edit there.",
           "# Party leaders are 'Leader', the PM 'Prime Minister' (above wm_spouse_titles.txt's holder entries); spouses take no rank."]
    for g in ("male", "female"):
        out += ["wm_party_leader_%s = {" % g, "\ttype = character", "\tgender = %s" % g, "\tspecial = holder",
                "\tpriority = 9700", "\ttitles = { %s }" % " ".join(parties), "\tflavourization_rules = {",
                "\t\tonly_holder = yes", "\t\tspouse_takes_title = no", "\t}", "}"]
        keys["wm_party_leader_%s" % g] = "Leader"
    for g in ("male", "female"):          # the PM leads a party too, but is Prime Minister first
        out += ["wm_prime_minister_%s = {" % g, "\ttype = character", "\tgender = %s" % g, "\tspecial = holder",
                "\tpriority = 9800", "\ttitles = { e_united_kingdom }", "\tflavourization_rules = {",
                "\t\tonly_holder = yes", "\t\tspouse_takes_title = no", "\t}", "}"]
        keys["wm_prime_minister_%s" % g] = "Prime Minister"
    # Vanilla's special title holders (the Pope, the Orthodox patriarchs...) name titles Westminster doesn't have
    van = MOD / "common" / "flavorization" / "00_title_holders.txt"
    van.write_text("# Westminster: replaces Crusader Kings III's own common/flavorization/00_title_holders.txt (Paradox\n"
                   "# Interactive), whose medieval titles don't exist here. Generated by westminster/tools/ui/build_ranks.py.\n",
                   encoding="utf-8-sig")
    dest = MOD / "common" / "flavorization" / "wm_party_leaders.txt"
    dest.write_text("\n".join(out) + "\n", encoding="utf-8-sig")


def main():
    keys = {}
    for f in FILES:
        for m in re.finditer(r"^ ([a-z][a-z0-9_]*)(?::\d*)? ", f.read_text(encoding="utf-8-sig"), re.M):
            k = m.group(1)
            first = k.split("_")[0]
            if first in RANKS and "wm_crown" not in k:
                name = RANKS[first]
                keys[k] = PLURALS[name] if k.endswith("_plural") else name
    for r, name in RANKS.items():                     # the plain keys too
        keys.setdefault(r, name)
        keys.setdefault(r + "_plural", PLURALS[name])
        if r in ("baron", "count", "duke", "king", "emperor"):
            keys.setdefault(r + "_female", name)
    # Royal-family titles (Prince, Infanta, Shahzada...): with parties as houses every member of the PM's party would be
    # a "Prince". Blanked, so $TIER$ is empty for them and only the name shows.
    for f in LOC.rglob("*.yml"):
        for m in re.finditer(r'^ ((?:prince|princess)(?:_[a-z0-9]+)*)(?::\d*)? "([^"]*)"', f.read_text(encoding="utf-8-sig"), re.M):
            k, v = m.groups()
            if not re.search(r"elect|archivist|desc|poem|tooltip|candidates|law", k) and len(v.split()) <= 2:
                keys[k] = ""
    write_party_leader_flavour(keys)
    out = ["l_english:", " # Generated by westminster/tools/ui/build_ranks.py - edit there."]
    out += [' %s: "%s"' % (k, v) for k, v in sorted(keys.items())]
    dest = MOD / "localization" / "english" / "replace" / "wm_ranks_l_english.yml"
    dest.write_text("\n".join(out) + "\n", encoding="utf-8-sig")
    print("rank and tier keys:", len(keys))


if __name__ == "__main__":
    main()
