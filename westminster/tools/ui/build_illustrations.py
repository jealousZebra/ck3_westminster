#!/usr/bin/env python3
"""Replaces the game's medieval scene lists with Westminster's modern scenes (pictures from fal_images.py).

    .venv/bin/python westminster/tools/ui/build_illustrations.py

- gfx/interface/illustrations/scripted_illustrations/ingame.txt: every in-game scene list (the background behind
  character portraits, location and holding views, private rooms) picks from a handful of modern scenes in
  gfx/interface/illustrations/wm/ instead of about 300 medieval ones. The names must stay vanilla's: the GUI asks
  for them.
- front_end_random.txt: the random front-end backgrounds become the loading-screen photos.
- loading_screens/loadscreen_settings.txt: only Westminster's loading screens.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
MOD = ROOT / "westminster"
ILL = MOD / "gfx" / "interface" / "illustrations"
LOADING = ["assassin", "baghdad", "castle", "council", "duel",      # vanilla names, our pictures (fal_images.py)
           "wm_commons", "wm_downing", "wm_holyrood", "wm_senedd", "wm_stormont", "wm_polling", "wm_count",
           "wm_conference", "wm_press"]
ENV = "environment_event_temple"            # vanilla's fallback lighting for portraits in front of a scene

# Scene list name -> [(picture in illustrations/wm/ or a path under illustrations/, trigger or None for the fallback)]
SCENES = {
    "character_view_bg": [("memorial", "is_alive = no"), ("office", None)],
    "character_location_exterior": [("street", None)],
    "character_religion_interior": [("loading_screens/wm_commons", None)],   # also the Leader of the House's card
    "religion_interior": [("loading_screens/wm_conference", None)],   # the ideology view, behind its leaders
    "religion_holding": [("town_hall", None)],                        # the ideology view's Heartlands tab
    "title_holding": [("town_hall", None)],
    "artifact_regional_pattern": [("office", None)],
    "character_private": [("memorial", "is_alive = no"), ("home", None)],
}


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8-sig")


def main():
    gen = "Generated by westminster/tools/ui/build_illustrations.py - edit there.\n"
    out = ["# Westminster: modern scenes in place of those in Crusader Kings III's own "
           "gfx/interface/illustrations/scripted_illustrations/ingame.txt (Paradox Interactive). " + gen]
    for name, entries in SCENES.items():
        out.append("%s = {\n" % name)
        for pic, trig in entries:
            t = "\t\ttrigger = { %s }\n" % trig if trig else ""
            ref = pic if "/" in pic else "wm/" + pic                # a scene in wm/, or another illustration
            out.append('\ttexture = {\n\t\treference = "%s.dds"\n%s\t}\n' % (ref, t))
        out.append('\tenvironment = {\n\t\treference = "%s"\n\t}\n}\n\n' % ENV)
    write(ILL / "scripted_illustrations" / "ingame.txt", "".join(out))
    write(ILL / "scripted_illustrations" / "front_end_random.txt",
          "# " + gen + "front_end_random_background = {\n" + "".join('\ttexture = {\n\t\treference = "loading_screens/%s.dds"\n\t}\n' % n for n in LOADING) + "}\n")
    write(ILL / "loading_screens" / "loadscreen_settings.txt", "# " + gen + "".join("%s = { priority = 2 }\n" % n for n in LOADING))
    print("scene lists: %d, loading screens: %d" % (len(SCENES), len(LOADING)))


if __name__ == "__main__":
    main()
