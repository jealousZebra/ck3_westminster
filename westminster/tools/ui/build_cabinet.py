#!/usr/bin/env python3
"""The Cabinet: ministers come from the Prime Minister's party (or the coalition partner), and the cabinet cards show
modern offices instead of medieval rooms.

    .venv/bin/python westminster/tools/ui/build_cabinet.py

- common/council_positions/00_council_positions.txt: vanilla's, with one extra condition in the valid_character of the
  five ministerial posts (not the spouse): wm_cabinet_eligible_trigger (common/scripted_triggers/wm_cabinet_triggers.txt).
  Rebuilt from vanilla each time.
- common/on_action/wm_cabinet_on_actions.txt: ministers who aren't eligible (from the bookmark, or after a change
  of PM or coalition) are dismissed at game start and every quarter,
  and empty posts are filled with the best-qualified colleague.
- gfx/interface/skinned/illustrations/council/bg_council_*.dds (and every culture skin's copy): crops of the fal.ai
  office photos.
"""
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent.parent
MOD = ROOT / "westminster"
sys.path.insert(0, str(Path(__file__).resolve().parents[3] / "common" / "tools"))
from ck3paths import GAME  # noqa: E402  (CK3_GAME_DIR overrides the Steam default)
FAL = ROOT / "art" / "fal"
POSTS = ["councillor_chancellor", "councillor_steward", "councillor_marshal", "councillor_spymaster", "councillor_court_chaplain"]
BACKGROUNDS = {"chancellor": "street", "steward": "decisions", "marshal": "dungeon", "spymaster": "faction",
               "chaplain": "council", "spouse": "home"}


def patch_positions():
    src = (GAME / "common/council_positions/00_council_positions.txt").read_text(encoding="utf-8-sig")
    out, n = "\n" + src, 0          # (the first post is on line 1)
    for post in POSTS:
        start = out.index("\n%s = {" % post)
        i = out.index("valid_character = {", start)
        j = i + len("valid_character = {")
        out = out[:j] + "\n\t\twm_cabinet_eligible_trigger = { PM = root.liege_or_court_owner }\t# Westminster: party colleagues" + out[j:]
        n += 1
    # The Leader of the House (vanilla's court chaplain) needn't share the PM's ideology or follow clergy rules
    old_trig = "can_be_court_chaplain_trigger = { COURT_OWNER = root.liege_or_court_owner }"
    if out.count(old_trig) != 1:
        raise SystemExit("council positions: expected one court chaplain trigger")
    out = out.replace(old_trig, "can_be_councillor_basics_trigger = yes\t# Westminster: no clergy rules")
    dest = MOD / "common/council_positions/00_council_positions.txt"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("# Westminster: Crusader Kings III's own common/council_positions/00_council_positions.txt (Paradox "
                    "Interactive), ministers limited to the PM's party colleagues, by westminster/tools/ui/build_cabinet.py"
                    " - edit there.\n" + out, encoding="utf-8-sig")
    (MOD / "common/scripted_triggers").mkdir(parents=True, exist_ok=True)
    (MOD / "common/scripted_triggers/wm_cabinet_triggers.txt").write_text("""# Generated by westminster/tools/ui/build_cabinet.py - edit there.
# Can this character (root) sit in $PM$'s Cabinet? Party colleagues, or the coalition partner's MPs; anyone if the
# PM has no party (before the parties are set up).
wm_cabinet_eligible_trigger = {
	OR = {
		NOT = { exists = $PM$.var:wm_party }
		var:wm_party ?= $PM$.var:wm_party
		AND = {
			has_global_variable = wm_coalition_partner
			var:wm_party ?= global_var:wm_coalition_partner
		}
	}
}
""", encoding="utf-8-sig")
    (MOD / "common/on_action").mkdir(parents=True, exist_ok=True)
    (MOD / "common/on_action/wm_cabinet_on_actions.txt").write_text("""# Generated by westminster/tools/ui/build_cabinet.py - edit there.
# Dismisses ministers who aren't the PM's party colleagues (the council's valid_character only stops new appointments),\n# then fills empty posts with the best-qualified colleague (the AI doesn't refill them, and a player PM starts with gaps).
on_game_start_after_lobby = {
	on_actions = { wm_cabinet_on_check }
}
quarterly_playable_pulse = {
	on_actions = { wm_cabinet_on_pulse }
}
wm_cabinet_on_pulse = {
	trigger = { has_title = title:e_united_kingdom }	# (the pulse runs for every playable character)
	on_actions = { wm_cabinet_on_check }
}
wm_cabinet_on_check = {
	effect = {
		title:e_united_kingdom.holder ?= {
			save_temporary_scope_as = wm_cab_pm
			every_councillor = {
				limit = {
					NOT = { this = scope:wm_cab_pm.primary_spouse }
					NOT = { wm_cabinet_eligible_trigger = { PM = scope:wm_cab_pm } }
				}
				scope:wm_cab_pm = { fire_councillor = prev }
			}
			if = {	# empty: the best-qualified colleague
				limit = { NOT = { exists = cp:councillor_chancellor } }
				ordered_vassal = {
					limit = { is_adult = yes is_imprisoned = no is_councillor = no wm_cabinet_eligible_trigger = { PM = scope:wm_cab_pm } }
					order_by = diplomacy
					save_temporary_scope_as = wm_cab_pick
				}
				if = {
					limit = { exists = scope:wm_cab_pick }
					assign_councillor_type = { type = councillor_chancellor target = scope:wm_cab_pick }
					clear_saved_scope = wm_cab_pick
				}
			}
			if = {	# empty: the best-qualified colleague
				limit = { NOT = { exists = cp:councillor_steward } }
				ordered_vassal = {
					limit = { is_adult = yes is_imprisoned = no is_councillor = no wm_cabinet_eligible_trigger = { PM = scope:wm_cab_pm } }
					order_by = stewardship
					save_temporary_scope_as = wm_cab_pick
				}
				if = {
					limit = { exists = scope:wm_cab_pick }
					assign_councillor_type = { type = councillor_steward target = scope:wm_cab_pick }
					clear_saved_scope = wm_cab_pick
				}
			}
			if = {	# empty: the best-qualified colleague
				limit = { NOT = { exists = cp:councillor_marshal } }
				ordered_vassal = {
					limit = { is_adult = yes is_imprisoned = no is_councillor = no wm_cabinet_eligible_trigger = { PM = scope:wm_cab_pm } }
					order_by = martial
					save_temporary_scope_as = wm_cab_pick
				}
				if = {
					limit = { exists = scope:wm_cab_pick }
					assign_councillor_type = { type = councillor_marshal target = scope:wm_cab_pick }
					clear_saved_scope = wm_cab_pick
				}
			}
			if = {	# empty: the best-qualified colleague
				limit = { NOT = { exists = cp:councillor_spymaster } }
				ordered_vassal = {
					limit = { is_adult = yes is_imprisoned = no is_councillor = no wm_cabinet_eligible_trigger = { PM = scope:wm_cab_pm } }
					order_by = intrigue
					save_temporary_scope_as = wm_cab_pick
				}
				if = {
					limit = { exists = scope:wm_cab_pick }
					assign_councillor_type = { type = councillor_spymaster target = scope:wm_cab_pick }
					clear_saved_scope = wm_cab_pick
				}
			}
			if = {	# empty: the best-qualified colleague
				limit = { NOT = { exists = cp:councillor_court_chaplain } }
				ordered_vassal = {
					limit = { is_adult = yes is_imprisoned = no is_councillor = no wm_cabinet_eligible_trigger = { PM = scope:wm_cab_pm } }
					order_by = learning
					save_temporary_scope_as = wm_cab_pick
				}
				if = {
					limit = { exists = scope:wm_cab_pick }
					assign_councillor_type = { type = councillor_court_chaplain target = scope:wm_cab_pick }
					clear_saved_scope = wm_cab_pick
				}
			}
		}
	}
}
""", encoding="utf-8-sig")
    return n


def backgrounds():
    for post, pic in BACKGROUNDS.items():
        van = Image.open(GAME / ("gfx/interface/skinned/illustrations/council/bg_council_%s.dds" % post))
        w, h = van.size
        im = Image.open(FAL / (pic + ".jpg")).convert("RGB")
        s = max(w / im.width, h / im.height)
        im = im.resize((round(im.width * s), round(im.height * s)), Image.LANCZOS)
        x0, y0 = (im.width - w) // 2, (im.height - h) // 2
        im = im.crop((x0, y0, x0 + w, y0 + h)).convert("RGBA")
        rel = "illustrations/council/bg_council_%s.dds" % post
        # gfx/interface/skinned/... is resolved per culture skin: the skins that have their own copy need ours too
        outs = [MOD / "gfx/interface/skinned" / rel] + [MOD / "gfx/interface/skins" / d.name / rel
                for d in sorted((GAME / "gfx/interface/skins").iterdir()) if (d / rel).exists()]
        for out in outs:
            out.parent.mkdir(parents=True, exist_ok=True)
            im.save(out, pixel_format="DXT1")
    return len(BACKGROUNDS)


def main():
    Image.MAX_IMAGE_PIXELS = None
    print("cabinet posts restricted to colleagues:", patch_positions())
    print("cabinet backgrounds:", backgrounds())


if __name__ == "__main__":
    main()
